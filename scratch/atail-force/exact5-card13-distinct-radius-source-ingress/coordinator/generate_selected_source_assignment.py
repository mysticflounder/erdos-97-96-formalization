#!/usr/bin/env python3
"""Generate the exact dense assignment for the distinct-source BV surface.

The verified direct and mirror reduced-union modules use the same natural-key
variable table.  This generator rebuilds both live 58,433-assertion streams,
checks that their complete 1,666-variable tables agree, and emits one shared
``BVExpr.Assignment`` plus bounded ``get``/``eval`` lemma modules.

This file deliberately does not prove any source assertion.  It is the exact
symbolic-to-packed-value bridge used by the selected semantic producers.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys


HERE = Path(__file__).resolve().parent
AUDIT = HERE.parent.parent / "exact5-card13-distinct-radius-source-ingress-audit"
sys.path.insert(0, str(AUDIT))

from distinct_source_terms import (  # noqa: E402
    EXPECTED_SOURCE_BITS,
    EXPECTED_VARIABLES,
    build_source_assertions,
    collect_variables,
    source_stream_sha256,
)


CHUNK_SIZE = 64
NAMESPACE = (
    "Problem97."
    "ATailExactFiveCard13DistinctRadiusSourceIngressCoordinatorScratch"
)


def slot_expression(info: dict[str, object]) -> str:
    atom = str(info["lean_atom"])
    sort = str(info["sort"])
    if sort == "Bool":
        return f"⟨BitVec.ofBool ({atom})⟩"
    if sort in {"Int-as-unsigned-4", "BitVec(7)"}:
        return f"⟨{atom}⟩"
    raise ValueError(f"unsupported source sort: {sort}")


def rarray_expression(entries: list[str], start: int = 0, indent: int = 2) -> str:
    """Render a balanced ``Lean.RArray`` with absolute branch pivots."""

    if not entries:
        raise ValueError("cannot construct an empty source assignment")
    if len(entries) == 1:
        return f".leaf {entries[0]}"
    split = len(entries) // 2
    pivot = start + split
    left = rarray_expression(entries[:split], start, indent + 2)
    right = rarray_expression(entries[split:], pivot, indent + 2)
    pad = " " * indent
    return f".branch {pivot}\n{pad}({left})\n{pad}({right})"


def argument_lines() -> str:
    return """    (rows : RowBits) (blockers : BlockerBits) (shell : ShellBits)
    (q w : RoleBits) (b1 : FirstRowBits)
    (parentFirst parentSecond : ParentRowBits)
    (connectivity : ConnectivityBits) (ranks : RankBits)"""


def argument_names() -> str:
    return (
        "rows blockers shell q w b1 parentFirst parentSecond "
        "connectivity ranks"
    )


def render_base(variables: list[tuple[str, dict[str, object]]]) -> str:
    assignment = rarray_expression([slot_expression(info) for _name, info in variables])
    return f'''/- Generated by `generate_selected_source_assignment.py`; do not edit. -/
import ParentRowIngressAdapters
import AggregateConnectivityPacking
import Std.Tactic.BVDecide.Reflect
import Lean.Data.RArray

/-! Exact dense assignment for the distinct-radius verified source surface. -/

namespace {NAMESPACE}

open ATailExactFiveCard13CnfIngressScratch
open ExactFiveCard13DistinctRadiusSourceIngressScratch
open Std.Tactic.BVDecide

set_option maxRecDepth 1000000
set_option maxHeartbeats 0
set_option linter.unusedVariables false

/-- The four-bit source encoding of one canonical role. -/
abbrev RoleBits := BitVec 4

/-- The 78 seven-bit ordinal-distance ranks. -/
abbrev RankBits := BitVec 546

/-- The source uses two names for the same packed parent-row accessor. -/
abbrev parentFirstBit := parentRowBit
abbrev parentSecondBit := parentRowBit

/-- Read one of the 78 seven-bit ordinal ranks. -/
abbrev rankAtom (ranks : RankBits) (index : Nat) : BitVec 7 :=
  ranks.extractLsb' (7 * index) 7

/-- Exact dense 1,666-variable assignment consumed by both verified orbits. -/
def selectedSourceAssignment
{argument_lines()} : BVExpr.Assignment :=
  {assignment}

end {NAMESPACE}
'''


def render_chunk(
    chunk: int,
    variables: list[tuple[str, dict[str, object]]],
) -> str:
    declarations: list[str] = []
    for _name, info in variables:
        index = int(info["index"])
        width = int(info["width"])
        atom = str(info["lean_atom"])
        expected = atom if info["sort"] != "Bool" else f"BitVec.ofBool ({atom})"
        slot = slot_expression(info)
        declarations.append(f'''@[simp] theorem selectedSourceAssignment_get_{index:04d}
{argument_lines()} :
    (selectedSourceAssignment {argument_names()}).get {index} = {slot} := by
  unfold BVExpr.Assignment.get
  rw [Lean.RArray.get_eq_getImpl]
  rfl

@[simp 1100] theorem selectedSourceAssignment_eval_var_{index:04d}
{argument_lines()} :
    BVExpr.eval (selectedSourceAssignment {argument_names()})
      ((.var {index}) : BVExpr {width}) = {expected} := by
  rw [BVExpr.eval_var, selectedSourceAssignment_get_{index:04d}]
  simp
''')
    return f'''/- Generated by `generate_selected_source_assignment.py`; do not edit. -/
import SelectedSourceAssignmentBase

/-! Bounded assignment lookup and variable-evaluation lemmas. -/

namespace {NAMESPACE}

open ATailExactFiveCard13CnfIngressScratch
open ExactFiveCard13DistinctRadiusSourceIngressScratch
open Std.Tactic.BVDecide

set_option maxRecDepth 1000000
set_option maxHeartbeats 0
set_option linter.unusedVariables false

{"\n".join(declarations)}

end {NAMESPACE}
'''


def render_aggregate(chunk_count: int) -> str:
    imports = "\n".join(
        f"import SelectedSourceAssignmentChunk{chunk:03d}"
        for chunk in range(chunk_count)
    )
    return f'''/- Generated by `generate_selected_source_assignment.py`; do not edit. -/
{imports}

/-! Aggregate import for every generated assignment evaluation chunk. -/

namespace {NAMESPACE}

/-- Marker that every variable in the exact dense table has a checked eval lemma. -/
theorem selectedSourceAssignment_variable_count : {EXPECTED_VARIABLES} = {EXPECTED_VARIABLES} := rfl

end {NAMESPACE}
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", type=Path, default=HERE / "selected-assignment")
    parser.add_argument("--chunk-size", type=int, default=CHUNK_SIZE)
    args = parser.parse_args()
    if args.chunk_size <= 0:
        raise ValueError("chunk size must be positive")

    assertions: dict[str, list[object]] = {}
    variables: dict[str, dict[str, dict[str, object]]] = {}
    for orientation in ("direct", "mirror"):
        current, _counts, _outer, _ranks = build_source_assertions(orientation)
        assertions[orientation] = current
        variables[orientation] = collect_variables(current)

    if variables["direct"] != variables["mirror"]:
        raise AssertionError("direct/mirror variable table drift")
    ordered = sorted(
        variables["direct"].items(), key=lambda item: int(item[1]["index"])
    )
    if [int(info["index"]) for _name, info in ordered] != list(range(EXPECTED_VARIABLES)):
        raise AssertionError("variable table is not dense and zero based")
    if sum(int(info["width"]) for _name, info in ordered) != EXPECTED_SOURCE_BITS:
        raise AssertionError("source bit width drift")

    args.output_dir.mkdir(parents=True, exist_ok=True)
    for stale in args.output_dir.glob("SelectedSourceAssignment*.lean"):
        stale.unlink()
    (args.output_dir / "SelectedSourceAssignmentBase.lean").write_text(
        render_base(ordered), encoding="utf-8"
    )
    chunks = [
        ordered[start : start + args.chunk_size]
        for start in range(0, len(ordered), args.chunk_size)
    ]
    for chunk, entries in enumerate(chunks):
        (args.output_dir / f"SelectedSourceAssignmentChunk{chunk:03d}.lean").write_text(
            render_chunk(chunk, entries), encoding="utf-8"
        )
    (args.output_dir / "SelectedSourceAssignment.lean").write_text(
        render_aggregate(len(chunks)), encoding="utf-8"
    )

    digest = hashlib.sha256()
    for _name, info in ordered:
        digest.update(str(info).encode())
        digest.update(b"\n")
    print(f"variables={len(ordered)}")
    print(f"bits={sum(int(info['width']) for _name, info in ordered)}")
    print(f"chunks={len(chunks)}")
    print(f"variable_table_sha256={digest.hexdigest()}")
    for orientation in ("direct", "mirror"):
        print(
            f"{orientation}_source_stream_sha256="
            f"{source_stream_sha256(assertions[orientation])}"
        )


if __name__ == "__main__":
    main()
