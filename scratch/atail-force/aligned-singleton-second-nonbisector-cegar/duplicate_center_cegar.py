#!/usr/bin/env python3
"""Checked duplicate-center equality-closure cuts for the bounded CEGAR lane.

Rows generate equalities between unordered distance edges: if ``x`` and ``y``
belong to the selected row at ``c``, then ``|cx| = |cy|``.  Reversal of an
edge is built into the unordered representation.  A cut is emitted only when
four checked paths make two distinct centers equidistant from the same three
distinct carrier points.

This is the finite certificate shape proved sound by
``Problem97.Census554.EqualityCore.EdgeClosure.sound`` and
``Problem97.Census554.EqualityCore.not_realizes_of_duplicateCenterCore``.
The Python checker is not a kernel replay; its output remains part of the
bounded encoder trust boundary.
"""

from __future__ import annotations

from collections import defaultdict, deque
from itertools import combinations
from typing import Iterable


KIND = "DUPLICATE_CENTER_EQUALITY_CORE"
KERNEL_BASIS = (
    "Problem97.Census554.EqualityCore.EdgeClosure.sound",
    "Problem97.Census554.EqualityCore.not_realizes_of_duplicateCenterCore",
)
PATH_NAMES = ("ap_aq", "ap_ar", "bp_bq", "bp_br")

Edge = tuple[int, int]
Member = tuple[int, int]
Step = tuple[int, int, int]
Graph = dict[Edge, list[tuple[Edge, Step]]]


def unordered_edge(first: int, second: int) -> Edge:
    return (first, second) if first <= second else (second, first)


def _checked_rows(
    rows: dict[int, Iterable[int]], n: int
) -> dict[int, tuple[int, ...]]:
    answer: dict[int, tuple[int, ...]] = {}
    for center in range(n):
        raw = tuple(int(point) for point in rows.get(center, ()))
        if len(set(raw)) != len(raw):
            raise ValueError(f"row {center} contains a duplicate point")
        if any(point < 0 or point >= n for point in raw):
            raise ValueError(f"row {center} contains an out-of-range point")
        if center in raw:
            raise ValueError(f"row {center} contains its center")
        answer[center] = tuple(sorted(raw))
    return answer


def equality_graph(rows: dict[int, Iterable[int]], n: int) -> Graph:
    """Build the edge-equality graph generated by positive row memberships."""
    checked = _checked_rows(rows, n)
    graph: dict[Edge, list[tuple[Edge, Step]]] = defaultdict(list)
    for center, points in checked.items():
        for left, right in combinations(points, 2):
            first = unordered_edge(center, left)
            second = unordered_edge(center, right)
            step = (center, left, right)
            graph[first].append((second, step))
            graph[second].append((first, step))
    for neighbors in graph.values():
        neighbors.sort(key=lambda item: (item[0], item[1]))
    return dict(graph)


def _components(graph: Graph) -> dict[Edge, Edge]:
    component_of: dict[Edge, Edge] = {}
    for start in sorted(graph):
        if start in component_of:
            continue
        queue = [start]
        component: list[Edge] = []
        component_of[start] = start
        while queue:
            current = queue.pop()
            component.append(current)
            for neighbor, _step in graph.get(current, ()):
                if neighbor not in component_of:
                    component_of[neighbor] = start
                    queue.append(neighbor)
        representative = min(component)
        for edge in component:
            component_of[edge] = representative
    return component_of


def _path(graph: Graph, first: Edge, last: Edge) -> list[Step]:
    if first == last:
        return []
    queue: deque[Edge] = deque([first])
    previous: dict[Edge, tuple[Edge, Step] | None] = {first: None}
    while queue:
        current = queue.popleft()
        for neighbor, step in graph.get(current, ()):
            if neighbor in previous:
                continue
            previous[neighbor] = (current, step)
            if neighbor == last:
                queue.clear()
                break
            queue.append(neighbor)
    if last not in previous:
        raise ValueError(f"no equality-closure path from {first} to {last}")
    reverse_steps: list[Step] = []
    current = last
    while current != first:
        entry = previous[current]
        assert entry is not None
        current, step = entry
        reverse_steps.append(step)
    reverse_steps.reverse()
    return reverse_steps


def _serialized_path(steps: Iterable[Step]) -> list[dict[str, int]]:
    return [
        {"center": center, "left": left, "right": right}
        for center, left, right in steps
    ]


def find_duplicate_center_cores(
    rows: dict[int, Iterable[int]],
    n: int,
    *,
    limit: int = 32,
) -> list[dict[str, object]]:
    """Return up to ``limit`` deterministic path-supported duplicate cores."""
    if limit < 0:
        raise ValueError("limit must be nonnegative")
    if limit == 0:
        return []
    graph = equality_graph(rows, n)
    component_of = _components(graph)

    triple_centers: dict[
        tuple[int, int, int], list[tuple[int, Edge]]
    ] = defaultdict(list)
    for center in range(n):
        by_component: dict[Edge, list[int]] = defaultdict(list)
        for point in range(n):
            if point == center:
                continue
            edge = unordered_edge(center, point)
            representative = component_of.get(edge, edge)
            by_component[representative].append(point)
        for representative, points in sorted(by_component.items()):
            for triple in combinations(sorted(points), 3):
                triple_centers[triple].append((center, representative))

    answer: list[dict[str, object]] = []
    seen_antecedents: set[tuple[Member, ...]] = set()
    for points in sorted(triple_centers):
        p, q, r = points
        centers = sorted(triple_centers[points])
        for (a, _), (b, _) in combinations(centers, 2):
            paths = {
                "ap_aq": _path(
                    graph, unordered_edge(a, p), unordered_edge(a, q)
                ),
                "ap_ar": _path(
                    graph, unordered_edge(a, p), unordered_edge(a, r)
                ),
                "bp_bq": _path(
                    graph, unordered_edge(b, p), unordered_edge(b, q)
                ),
                "bp_br": _path(
                    graph, unordered_edge(b, p), unordered_edge(b, r)
                ),
            }
            item: dict[str, object] = {
                "kind": KIND,
                "centers": [a, b],
                "points": [p, q, r],
                "paths": {
                    name: _serialized_path(paths[name]) for name in PATH_NAMES
                },
                "kernel_basis": list(KERNEL_BASIS),
            }
            antecedents = validate_refinement(item, n)
            if antecedents in seen_antecedents:
                continue
            seen_antecedents.add(antecedents)
            item["antecedent_size"] = len(antecedents)
            item["antecedents"] = [
                {"center": center, "point": point}
                for center, point in antecedents
            ]
            answer.append(item)
            if len(answer) >= limit:
                return answer
    return answer


def _checked_int(value: object, *, name: str, n: int) -> int:
    if not isinstance(value, int) or isinstance(value, bool):
        raise ValueError(f"{name} is not an integer")
    if value < 0 or value >= n:
        raise ValueError(f"{name} is out of range")
    return value


def _walk_checked_path(
    raw_path: object,
    *,
    first: Edge,
    last: Edge,
    name: str,
    n: int,
) -> set[Member]:
    if not isinstance(raw_path, list) or not raw_path:
        raise ValueError(f"{name} is malformed or empty")
    current = first
    antecedents: set[Member] = set()
    for index, raw_step in enumerate(raw_path):
        if not isinstance(raw_step, dict):
            raise ValueError(f"{name}[{index}] is not an object")
        center = _checked_int(raw_step.get("center"), name="center", n=n)
        left = _checked_int(raw_step.get("left"), name="left", n=n)
        right = _checked_int(raw_step.get("right"), name="right", n=n)
        if left == right or center in (left, right):
            raise ValueError(f"{name}[{index}] is a degenerate row step")
        source = unordered_edge(center, left)
        target = unordered_edge(center, right)
        if current == source:
            current = target
        elif current == target:
            current = source
        else:
            raise ValueError(f"{name}[{index}] is not composable")
        antecedents.add((center, left))
        antecedents.add((center, right))
    if current != last:
        raise ValueError(f"{name} has the wrong endpoint")
    return antecedents


def validate_refinement(item: dict[str, object], n: int) -> tuple[Member, ...]:
    """Validate a saved core and return its exact positive antecedent atoms."""
    if item.get("kind") != KIND:
        raise ValueError("unexpected duplicate-center refinement kind")
    raw_centers = item.get("centers")
    raw_points = item.get("points")
    raw_paths = item.get("paths")
    if not isinstance(raw_centers, list) or len(raw_centers) != 2:
        raise ValueError("duplicate-center core has malformed centers")
    if not isinstance(raw_points, list) or len(raw_points) != 3:
        raise ValueError("duplicate-center core has malformed points")
    if not isinstance(raw_paths, dict) or set(raw_paths) != set(PATH_NAMES):
        raise ValueError("duplicate-center core has malformed paths")
    a, b = (
        _checked_int(value, name="center", n=n) for value in raw_centers
    )
    p, q, r = (_checked_int(value, name="point", n=n) for value in raw_points)
    if a == b:
        raise ValueError("duplicate-center core centers are equal")
    if len({p, q, r}) != 3:
        raise ValueError("duplicate-center core points are not distinct")

    endpoints = {
        "ap_aq": (unordered_edge(a, p), unordered_edge(a, q)),
        "ap_ar": (unordered_edge(a, p), unordered_edge(a, r)),
        "bp_bq": (unordered_edge(b, p), unordered_edge(b, q)),
        "bp_br": (unordered_edge(b, p), unordered_edge(b, r)),
    }
    antecedents: set[Member] = set()
    for name in PATH_NAMES:
        first, last = endpoints[name]
        antecedents.update(
            _walk_checked_path(
                raw_paths[name], first=first, last=last, name=name, n=n
            )
        )
    return tuple(sorted(antecedents))
