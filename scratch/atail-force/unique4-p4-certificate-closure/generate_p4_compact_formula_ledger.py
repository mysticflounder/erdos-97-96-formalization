#!/usr/bin/env python3
"""Generate the source-authenticated P4 compact-CNF ledger.

The input is the ordered compact occurrence ledger emitted next to the DIMACS
CNF.  This generator rejects a non-contiguous output order, zero literals, or
the wrong row count before writing Lean.  It deliberately records only the
three stable clause indices in Lean provenance; the full family and literal
metadata remains authenticated by the SHA-256 of the JSONL input in the
generated file header.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
INPUT = (
    ROOT.parent
    / "unique4-exact-two-core-map"
    / "generated"
    / "p4-seed0-compact"
    / "p4-seed0-compact-occurrences.jsonl"
)
OUTPUT = ROOT / "P4CompactFormulaLedger.lean"
EXPECTED_COUNT = 19_048


def lean_string_chunks(rows: list[str], *, rows_per_chunk: int = 100) -> str:
    """Render semicolon-delimited rows as bounded Lean string literals."""
    chunks = [
        ";".join(rows[offset : offset + rows_per_chunk])
        for offset in range(0, len(rows), rows_per_chunk)
    ]
    # Keep the delimiter at the end of each non-final literal, so the Lean
    # source can use String.join without changing the encoded row sequence.
    return ",\n  ".join(
        f'"{chunk}{";" if index + 1 < len(chunks) else ""}"'
        for index, chunk in enumerate(chunks)
    )


def main() -> None:
    raw = INPUT.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    rows = [json.loads(line) for line in raw.splitlines() if line]
    if len(rows) != EXPECTED_COUNT:
        raise SystemExit(f"expected {EXPECTED_COUNT} rows, found {len(rows)}")
    for expected, row in enumerate(rows, start=1):
        if row["output_clause_index"] != expected:
            raise SystemExit(
                f"non-contiguous output order at row {expected}: "
                f"{row['output_clause_index']}"
            )
        dense = row["dense_literals"]
        if not dense or any(not isinstance(lit, int) or lit == 0 for lit in dense):
            raise SystemExit(f"invalid dense literals at output clause {expected}")

    ledger = lean_string_chunks(
        [",".join(str(lit) for lit in row["dense_literals"]) for row in rows]
    )
    provenance = lean_string_chunks(
        [
            "{output},{core},{terminal}".format(
                output=row["output_clause_index"],
                core=row["source_core_clause_index"],
                terminal=row["source_terminal_clause_index"],
            )
            for row in rows
        ]
    )
    output = f'''/-
Copyright (c) 2026 Adam McKenna. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Adam McKenna
-/

import P4CertificateSemantics

/-!
# P4 compact formula ledger

Generated by `generate_p4_compact_formula_ledger.py` from
`p4-seed0-compact-occurrences.jsonl` (SHA-256 `{digest}`).  The source JSONL
contains the complete family label, source literals, terminal literals, and
ordered dense literals for each row.  This Lean file retains the ordered dense
ledger and its stable source/core/terminal indices, then checks that ledger
against the compact checkpoint parser.

This is an artifact-authentication boundary only.  It does not establish that
any geometric valuation satisfies the ledger.
-/

namespace Problem97.P4ExactTwoCertificateClosureScratch

open Problem97.CheckpointedRup.CompactBoundary

/-- Stable source indices for one output-order compact clause. -/
structure CompactClauseProvenance where
  outputClauseIndex : Nat
  sourceCoreClauseIndex : Nat
  sourceTerminalClauseIndex : Nat
  deriving Repr, DecidableEq

/-- The exact count of output-order clauses in the compact P4 occurrence ledger. -/
def compactFormulaLedgerCount : Nat := {EXPECTED_COUNT}

/-- SHA-256 of the JSONL source occurrence ledger used by this generated file. -/
def compactFormulaLedgerSourceSha256 : String := "{digest}"

/-- Compact encoding of output-order signed-DIMACS clauses from the source ledger. -/
private def compactFormulaLedgerEncoded : String := String.join [
  {ledger}
]

private def decodeIntClause? (row : String) : Option (List Int) :=
  (row.splitOn ",").mapM String.toInt?

private def decodeCompactFormulaLedger? (encoded : String) : Option (List (List Int)) :=
  (encoded.splitOn ";").mapM decodeIntClause?

/-- Output-order signed-DIMACS clauses from the source-authenticated P4 ledger. -/
def compactFormulaLedger : List (List Int) :=
  match decodeCompactFormulaLedger? compactFormulaLedgerEncoded with
  | some clauses => clauses
  | none => []

/-- Public name used by the source-to-checkpoint consumer. -/
def p4CompactLedger : List (List Int) := compactFormulaLedger

/-- Compact encoding of source/core/terminal indices in output order. -/
private def compactFormulaProvenanceEncoded : String := String.join [
  {provenance}
]

private def decodeCompactClauseProvenance? (row : String) : Option CompactClauseProvenance :=
  match row.splitOn "," with
  | [output, core, terminal] =>
      match output.toNat?, core.toNat?, terminal.toNat? with
      | some outputClauseIndex, some sourceCoreClauseIndex, some sourceTerminalClauseIndex =>
          some {{ outputClauseIndex, sourceCoreClauseIndex, sourceTerminalClauseIndex }}
      | _, _, _ => none
  | _ => none

/-- Source/core/terminal provenance in the same order as `compactFormulaLedger`. -/
def compactFormulaProvenance : List CompactClauseProvenance :=
  match (compactFormulaProvenanceEncoded.splitOn ";").mapM decodeCompactClauseProvenance? with
  | some provenance => provenance
  | none => []

theorem compactFormulaLedger_length : compactFormulaLedger.length = compactFormulaLedgerCount := by
  native_decide

theorem compactFormulaProvenance_length :
    compactFormulaProvenance.length = compactFormulaLedgerCount := by
  native_decide

/-- The occurrence-ledger clause order is exactly the compact checkpoint-0 parser order. -/
theorem compactFormulaLedger_eq_checkpoint0 :
    compactFormulaLedger = signedClausesOfFormula
      (formulaOfCompact (n := CompactWindowedRupReplay.n)
        CompactWindowedRupReplay.Checkpoint.C0000.text) := by
  native_decide

/-- The checkpoint parser's signed clauses are precisely the P4 source ledger. -/
theorem checkpoint0_signedClauses_eq_p4CompactLedger :
    signedClausesOfFormula
      (formulaOfCompact (n := CompactWindowedRupReplay.n)
        CompactWindowedRupReplay.Checkpoint.C0000.text) = p4CompactLedger := by
  exact compactFormulaLedger_eq_checkpoint0.symm

#print axioms compactFormulaLedger_eq_checkpoint0
#print axioms checkpoint0_signedClauses_eq_p4CompactLedger

end Problem97.P4ExactTwoCertificateClosureScratch
'''
    OUTPUT.write_text(output)
    print(f"wrote {OUTPUT} from {len(rows)} rows; sha256={digest}")


if __name__ == "__main__":
    main()
