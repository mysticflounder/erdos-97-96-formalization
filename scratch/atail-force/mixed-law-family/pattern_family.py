#!/usr/bin/env python3
r"""The COMPLETE support-local law family, equalities AND disequalities.

Every law mined so far in this lane is pure-equality: a set of co-radiality
atoms whose simultaneous truth is metrically impossible.  That family is
generated by a one-way oracle -- `eqonly_direct.py:213` asserts

    ev(y,u,v)  ->  d(y,u) = d(y,v)

so a FALSE atom constrains nothing and a metric realization is free to satisfy
extra equalities the Boolean layer explicitly forbids (the layer's N block caps
each co-radiality class at four).  Consequently no pure-equality bank, however
complete, can express a law of the form "these equalities FORCE a further
equality", and the lane's covering analysis
(`scratch/atail-force/lcap14-global-parent-surface/REPORT.md`) identifies laws
of exactly that shape as the missing general-n content.

Here the oracle is biconditional on a k-point support.  The layer carries an
`ev` variable for every (center, unordered pair) triple, so a layer model fixes
the COMPLETE equality pattern of the distance table; the faithful oracle
therefore asserts, for every triple inside the support,

    d(y,u) = d(y,v)   if the atom is true,      d(y,u) != d(y,v)   if false.

A complete pattern on k points is a tuple of set partitions, one per center,
of the other k-1 points.  Deciding all of them at k = 4 and k = 5 is
exhaustive: 5^4 = 625 and 15^5 = 759,375 tuples, cut by roughly the order of
the dihedral group of the k-cycle.  Each UNSAT pattern is then minimized to a
weakest mixed law -- drop equalities and disequalities while UNSAT survives --
and a law that retains at least one disequality is a genuine forced-equality
law, outside the pure-equality family by construction.

Soundness of the general-n reading: the axiom block is the same support-local
family used throughout the lane (positivity, strict triangle on all triples,
both strict Kalmanson inequalities per cyclic 4-subset of the support), taken
verbatim from `eqonly_direct.metric_axioms`.  It is a relaxation of planar
realizability, so UNSAT is a sound refutation at every n containing those k
points in that cyclic order, and cardinality-free.  SAT is not a realizability
claim.

Blocking form for the Boolean layer: a mixed law with equalities E and
disequalities N contributes the clause

    (\/_{e in E} -ev_e)  \/  (\/_{d in N} ev_d)

which is a normal clause with both polarities -- expressible in the layer,
unlike anything the pure-equality bank produces.

--smoke validates the oracle against known results before any production run.
"""

from __future__ import annotations

import argparse
import itertools
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from z3 import Real, Solver, sat, unsat  # noqa: E402

from eqonly_direct import metric_axioms  # noqa: E402

# The smallest pure-equality law in the lane's complete family: two atoms on
# four cyclic points, killed by one strict Kalmanson inequality.  Recorded in
# lcap14-global-parent-surface/REPORT.md as absent from the CEGAR bank.
KALMANSON_TWO_ATOM = ((0, 1, 2), (3, 1, 2))


def partitions(items):
    """Every set partition of `items`, as a tuple of sorted blocks."""
    items = list(items)
    if not items:
        yield ()
        return
    first, rest = items[0], items[1:]
    for sub in partitions(rest):
        # first joins an existing block ...
        for i in range(len(sub)):
            yield sub[:i] + (tuple(sorted((first,) + sub[i])),) + sub[i + 1:]
        # ... or starts its own
        yield sub + ((first,),)


def pattern_equalities(k, pattern):
    """Equality atoms (center, lo, hi) of a complete pattern.

    `pattern[y]` is the partition of the points other than `y` induced by
    distance from `y`: two points share a block exactly when they are
    co-radial from `y`.
    """
    out = set()
    for y in range(k):
        for block in pattern[y]:
            for u, v in itertools.combinations(sorted(block), 2):
                out.add((y, u, v))
    return frozenset(out)


def all_triples(k):
    return frozenset(
        (y, u, v)
        for y in range(k)
        for u, v in itertools.combinations([p for p in range(k) if p != y], 2))


def dihedral(k):
    """The 2k maps of the k-cycle, as point relabelings."""
    out = []
    for rot in range(k):
        for reflect in (False, True):
            if reflect:
                out.append(tuple((rot - i) % k for i in range(k)))
            else:
                out.append(tuple((rot + i) % k for i in range(k)))
    return out


def relabel(atoms, perm):
    out = set()
    for (y, u, v) in atoms:
        a, b = perm[u], perm[v]
        out.add((perm[y], min(a, b), max(a, b)))
    return frozenset(out)


def canonical(k, atoms, group=None):
    group = group or dihedral(k)
    return min(tuple(sorted(relabel(atoms, p))) for p in group)


def positivity_only(s, k):
    """Positivity alone: distances as free positive reals, no geometry."""
    d = {}
    for u, v in itertools.combinations(range(k), 2):
        d[(u, v)] = Real(f"d_{u}_{v}")
        s.add(d[(u, v)] > 0)
    return d, lambda u, v: d[(min(u, v), max(u, v))]


def no_kalmanson(s, k):
    """Positivity and strict triangle, but NOT Kalmanson.

    Kalmanson is the only order-dependent part of the support-local family: it
    is asserted per cyclic 4-subset and presumes the points sit in that cyclic
    order.  So a law that stays UNSAT with Kalmanson dropped holds for EVERY
    relabeling of its support, not just the order-preserving ones, and may be
    placed over all k! images instead of C(n,k)*2k.  That is a strictly larger
    body of blocking content from the same law.
    """
    d = {}
    for u, v in itertools.combinations(range(k), 2):
        d[(u, v)] = Real(f"d_{u}_{v}")
        s.add(d[(u, v)] > 0)

    def D(u, v):
        return d[(min(u, v), max(u, v))]

    for x, y, z in itertools.combinations(range(k), 3):
        s.add(D(x, z) < D(x, y) + D(y, z))
        s.add(D(x, y) < D(x, z) + D(y, z))
        s.add(D(y, z) < D(x, y) + D(x, z))
    return d, D


def decide(k, eqs, neqs, timeout_ms=0, axioms=metric_axioms):
    """Realizability of a mixed law under `axioms`.

    `axioms=metric_axioms` is the lane's support-local family.
    `axioms=positivity_only` drops triangle and Kalmanson, so UNSAT there means
    the law is a consequence of equality-graph algebra alone -- transitivity
    among the distances -- which the Boolean layer's T block already enforces.
    Such a law is not new content, however it was mined.
    """
    s = Solver()
    if timeout_ms:
        s.set("timeout", timeout_ms)
    _, D = axioms(s, k)
    for (y, u, v) in sorted(eqs):
        s.add(D(y, u) == D(y, v))
    for (y, u, v) in sorted(neqs):
        s.add(D(y, u) != D(y, v))
    res = s.check()
    return "sat" if res == sat else ("unsat" if res == unsat else "unknown")


def minimize(k, eqs, neqs):
    """Weakest mixed law: drop atoms from both sides while UNSAT survives.

    Dropping an equality frees the pair to differ; dropping a disequality frees
    it to coincide.  Both are genuine weakenings, so what survives is a law
    whose every atom is load-bearing.
    """
    eqs, neqs = set(eqs), set(neqs)
    changed = True
    while changed:
        changed = False
        for atom in sorted(eqs):
            if decide(k, eqs - {atom}, neqs) == "unsat":
                eqs.discard(atom)
                changed = True
                break
        if changed:
            continue
        for atom in sorted(neqs):
            if decide(k, eqs, neqs - {atom}) == "unsat":
                neqs.discard(atom)
                changed = True
                break
    return frozenset(eqs), frozenset(neqs)


def smoke() -> int:
    failures = 0

    def check(label, got, want):
        nonlocal failures
        ok = got == want
        failures += 0 if ok else 1
        print(f"smoke {label}: {got} (want {want}) {'OK' if ok else 'FAIL'}")
        return ok

    # 1. the generic pattern -- every distance distinct -- must be realizable,
    #    otherwise the disequality half of the encoding is broken.
    k = 4
    triples = all_triples(k)
    check("k=4 all-disequalities", decide(k, frozenset(), triples), "sat")

    # 2. the known two-atom Kalmanson law must be UNSAT with no disequalities,
    #    and must stay UNSAT with the full complementary disequality set.
    eqs = frozenset(KALMANSON_TWO_ATOM)
    check("k=4 kalmanson law, equalities only", decide(k, eqs, frozenset()),
          "unsat")
    check("k=4 kalmanson law, complete pattern",
          decide(k, eqs, triples - eqs), "unsat")

    # 3. minimizing that complete pattern must recover exactly the two
    #    equalities and discard every disequality: the law is pure-equality,
    #    so a disequality surviving here would mean minimize() is unsound.
    meqs, mneqs = minimize(k, eqs, triples - eqs)
    check("k=4 kalmanson minimized equalities", tuple(sorted(meqs)),
          tuple(sorted(eqs)))
    check("k=4 kalmanson minimized disequalities", len(mneqs), 0)

    # 4. each single atom of that law must be satisfiable on its own, so the
    #    law is minimal and the axiom block is not secretly stronger.
    for atom in sorted(eqs):
        check(f"k=4 single equality {atom}",
              decide(k, frozenset({atom}), frozenset()), "sat")

    # 4b. the algebraic filter must separate transitivity from geometry.
    #     Equal sides forcing the third is equality-graph algebra; two centers
    #     on one perpendicular bisector needs a strict Kalmanson inequality.
    equilateral = (frozenset({(1, 2, 3), (2, 1, 3)}), frozenset({(3, 1, 2)}))
    check("equilateral law is algebraic",
          decide(k, *equilateral, axioms=positivity_only), "unsat")
    check("kalmanson law is not algebraic",
          decide(k, eqs, frozenset(), axioms=positivity_only), "sat")

    # 5. partition/pattern plumbing: counts must match the Bell numbers, and
    #    equality extraction must invert on a hand-checked case.
    check("partitions of 3", len(list(partitions([1, 2, 3]))), 5)
    check("partitions of 4", len(list(partitions([1, 2, 3, 4]))), 15)
    check("partitions of 5", len(list(partitions([1, 2, 3, 4, 5]))), 52)
    hand = ((( 1, 2), (3,)), ((0, 2, 3),), ((0, 1), (3,)), ((0,), (1, 2)))
    check("pattern_equalities on a hand case",
          tuple(sorted(pattern_equalities(4, hand))),
          ((0, 1, 2), (1, 0, 2), (1, 0, 3), (1, 2, 3), (2, 0, 1), (3, 1, 2)))

    # 6. the dihedral group has order 2k and canonicalization is invariant
    #    under it.
    check("dihedral order k=5", len(set(dihedral(5))), 10)
    base = frozenset({(0, 1, 3), (2, 1, 4)})
    canons = {canonical(5, relabel(base, p)) for p in dihedral(5)}
    check("canonical invariance", len(canons), 1)

    print(f"smoke: {failures} failures")
    return 1 if failures else 0


def enumerate_family(k, timeout_ms, progress_every, out):
    """Decide every complete pattern on k points, up to the dihedral group."""
    group = dihedral(k)
    universe = all_triples(k)
    per_center = [list(partitions([p for p in range(k) if p != y]))
                  for y in range(k)]
    total = 1
    for lst in per_center:
        total *= len(lst)
    print(f"[k={k}] {total} complete patterns before symmetry, "
          f"{len(universe)} triples, group order {len(group)}", flush=True)

    seen = set()
    laws = {}
    counts = dict(patterns=0, classes=0, sat=0, unsat=0, unknown=0,
                  equality_only_unsat=0, forced_equality=0,
                  forced_equality_algebraic=0, forced_equality_geometric=0)
    t0 = time.time()
    for pattern in itertools.product(*per_center):
        counts["patterns"] += 1
        eqs = pattern_equalities(k, pattern)
        key = canonical(k, eqs, group)
        if key in seen:
            continue
        seen.add(key)
        counts["classes"] += 1
        neqs = universe - eqs

        # A pattern already refuted by its equalities alone is covered by the
        # pure-equality bank; its disequalities are inert.  Filtering these
        # first is what makes the support-5 level affordable, and it is exactly
        # the population the existing bank represents.
        if decide(k, eqs, frozenset(), timeout_ms) == "unsat":
            counts["equality_only_unsat"] += 1
            continue

        status = decide(k, eqs, neqs, timeout_ms)
        counts[status] += 1
        if status == "unsat":
            # Equality-only was SAT and the complete pattern is UNSAT, so at
            # least one disequality is load-bearing: a forced-equality law.
            counts["forced_equality"] += 1
            if decide(k, eqs, neqs, axioms=positivity_only) == "unsat":
                counts["forced_equality_algebraic"] += 1
                continue
            counts["forced_equality_geometric"] += 1
            meqs, mneqs = minimize(k, eqs, neqs)
            lawkey = (canonical(k, meqs, group) if meqs else (),
                      tuple(sorted(mneqs)))
            if lawkey not in laws:
                laws[lawkey] = dict(
                    support=k,
                    equalities=[list(a) for a in sorted(meqs)],
                    disequalities=[list(a) for a in sorted(mneqs)],
                    forced_equality=bool(mneqs),
                    algebraic=False)
                print(f"[k={k}] GEOMETRIC forced-equality law "
                      f"{len(laws)}: E={sorted(meqs)} N={sorted(mneqs)}",
                      flush=True)
        if progress_every and counts["classes"] % progress_every == 0:
            print(f"[k={k}] {counts['classes']} classes "
                  f"({counts['patterns']}/{total} raw), "
                  f"{counts['equality_only_unsat']} equality-only unsat, "
                  f"{counts['sat']} sat, {counts['forced_equality']} forced-eq "
                  f"({counts['forced_equality_geometric']} geometric), "
                  f"{len(laws)} laws ({time.time() - t0:.0f}s)", flush=True)

    result = dict(support=k, seconds=round(time.time() - t0, 1),
                  raw_patterns=total, **counts,
                  distinct_laws=len(laws),
                  laws=sorted(laws.values(),
                              key=lambda d: (len(d["equalities"]),
                                             len(d["disequalities"]))))
    if out:
        out.write_text(json.dumps(result, indent=1) + "\n")
    print(f"[k={k}] {counts['classes']} classes: "
          f"{counts['equality_only_unsat']} refuted by equalities alone "
          f"(pure-equality bank), {counts['sat']} realizable, "
          f"{counts['forced_equality']} forced-equality "
          f"({counts['forced_equality_algebraic']} algebraic / "
          f"{counts['forced_equality_geometric']} GEOMETRIC), "
          f"{counts['unknown']} unknown; {len(laws)} distinct geometric "
          f"forced-equality laws ({result['seconds']}s)", flush=True)
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--smoke", action="store_true")
    parser.add_argument("--k", type=int, default=4)
    parser.add_argument("--timeout", type=int, default=0,
                        help="per-pattern z3 timeout in ms, 0 = none")
    parser.add_argument("--progress-every", type=int, default=200)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()

    if args.smoke:
        return smoke()
    enumerate_family(args.k, args.timeout, args.progress_every, args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
