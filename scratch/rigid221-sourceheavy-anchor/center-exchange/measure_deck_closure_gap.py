"""Deck-closure gap measurement for the exact-12 common-five rule family.

Agreed action 1 of docs/exact12-v24-survivor-structural-analysis-2026-08-16.md:
count realizable placements admissible up to a wider role-symmetry action than
any installed rule.  This script measures the Klein widening generated by the
two involutions

  xy : (a, x, b, c, y) -> (a, y, b, c, x)   (installed: 21st bank)
  ab : (a, x, b, c, y) -> (b, x, a, c, y)   (not installed)

Because ``ab`` moves the triple row at ``c`` from {b, x, y} to {a, x, y}, a
per-order disjunction over the Klein group can only soundly block the UNION
pattern: supp(x) >= {a, b}, supp(y) >= {a, b}, supp(c) = {a, b, x, y} exactly
(supports have four elements).  A "gap pattern" is Klein-orientable in all 48
canonical orders while NEITHER ordered form (a, ., b, ., .) nor (b, ., a, ., .)
is center-exchange admissible, so no installed bank covers any usable branch.

Diagnostic only.  Nothing here authorizes a bank, a formula, or a wave.
Surplus-S3 triple cycling is a different shape and is NOT measured here.
"""

from __future__ import annotations

import itertools
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO_ROOT))

from census.card_head.exact12_center_exchange_all_order_common_five_membership_family_bank import (  # noqa: E402
    EXPECTED_ROLE_COUNT,
    EXPECTED_STRICT_ORBIT_ROLE_COUNT,
    EXPECTED_WIDENED_ORBIT_ROLE_COUNT,
    _admissible_center_exchange,
    _admissible_strict,
    _common_five,
    _positions,
    _row_realizable,
    _side_conditions,
    candidate_rows,
)

# The v24 cell-6 survivor cube (docs/exact12-v24-survivor-structural-analysis-
# 2026-08-16.md), for checking whether the one authenticated model already
# contains a gap-pattern instance.
V24_SURVIVOR_SUPPORTS = {
    0: {1, 2, 3, 4},
    1: {0, 3, 6, 8},
    2: {0, 1, 10, 11},
    3: {0, 5, 7, 9},
    4: {0, 5, 6, 10},
    5: {2, 7, 8, 11},
    6: {1, 4, 5, 11},
    7: {6, 8, 10, 11},
    8: {5, 6, 9, 11},
    9: {0, 3, 7, 11},
    10: {3, 5, 7, 8},
    11: {4, 5, 8, 10},
}


def _variants(a: int, x: int, b: int, c: int, y: int):
    """Side-condition-valid Klein variants of one placement."""

    for va, vx, vb, vc, vy in (
        (a, x, b, c, y),
        (a, y, b, c, x),
        (b, x, a, c, y),
        (b, y, a, c, x),
    ):
        if _side_conditions(va, vx, vb, vc, vy):
            yield (va, vx, vb, vc, vy)


def _klein_admissible(a: int, x: int, b: int, c: int, y: int) -> bool:
    variants = tuple(_variants(a, x, b, c, y))
    if not variants:
        return False
    return all(
        any(_common_five(position, *variant) for variant in variants)
        for position in _positions()
    )


def _installed_covered(a: int, x: int, b: int, c: int, y: int) -> bool:
    """Strict is a sub-orbit of center-exchange, so two checks suffice."""

    return _admissible_center_exchange(a, x, b, c, y) or (
        _admissible_center_exchange(b, x, a, c, y)
    )


def _quad_row_realizable(center: int, quad: tuple[int, ...]) -> bool:
    """supp(center) = quad exactly: the quad must be a candidate row."""

    ordered = tuple(sorted(quad))
    return any(
        tuple(sorted(candidate)) == ordered for candidate in candidate_rows(center)
    )


def main() -> None:
    # Harness validation against the frozen bank pins.
    widened = 0
    strict = 0
    delta_realizable = 0
    for a in range(12):
        for b in range(12):
            for c in range(12):
                for x in range(12):
                    for y in range(x + 1, 12):
                        if not _admissible_center_exchange(a, x, b, c, y):
                            continue
                        widened += 1
                        if _admissible_strict(a, x, b, c, y) or _admissible_strict(
                            a, y, b, c, x
                        ):
                            strict += 1
                        elif (
                            _row_realizable(x, (a, b) if a < b else (b, a))
                            and _row_realizable(y, (a, b) if a < b else (b, a))
                            and _row_realizable(c, tuple(sorted((b, x, y))))
                        ):
                            delta_realizable += 1
    assert widened == EXPECTED_WIDENED_ORBIT_ROLE_COUNT, widened
    assert strict == EXPECTED_STRICT_ORBIT_ROLE_COUNT, strict
    assert delta_realizable == EXPECTED_ROLE_COUNT, delta_realizable
    print(
        "harness validated against frozen pins: "
        f"widened={widened} strict={strict} delta_realizable={delta_realizable}"
    )

    # Klein gap: unordered in a<->b AND x<->y, so serialize a<b, x<y.
    gap: list[tuple[int, int, int, int, int]] = []
    for a, b in itertools.combinations(range(12), 2):
        for c in range(12):
            if c in (a, b):
                continue
            rest = [label for label in range(12) if label not in (a, b, c)]
            for x, y in itertools.combinations(rest, 2):
                if not _klein_admissible(a, x, b, c, y):
                    continue
                if _installed_covered(a, x, b, c, y):
                    continue
                gap.append((a, b, c, x, y))
    print(f"klein gap patterns (raw, a<b, x<y): {len(gap)}")

    realizable_gap = [
        (a, b, c, x, y)
        for a, b, c, x, y in gap
        if _row_realizable(x, (a, b))
        and _row_realizable(y, (a, b))
        and _quad_row_realizable(c, (a, b, x, y))
    ]
    print(f"klein gap patterns (realizable union rows): {len(realizable_gap)}")

    survivor_hits = [
        (a, b, c, x, y)
        for a, b, c, x, y in realizable_gap
        if {a, b} <= V24_SURVIVOR_SUPPORTS[x]
        and {a, b} <= V24_SURVIVOR_SUPPORTS[y]
        and V24_SURVIVOR_SUPPORTS[c] == {a, b, x, y}
    ]
    print(f"v24 survivor instances among realizable gap: {len(survivor_hits)}")
    for hit in survivor_hits:
        print(f"  survivor gap instance (a, b, c, x, y) = {hit}")

    if realizable_gap:
        sample = realizable_gap[: min(20, len(realizable_gap))]
        print("first realizable gap patterns (a, b, c, x, y):")
        for pattern in sample:
            print(f"  {pattern}")


if __name__ == "__main__":
    main()
