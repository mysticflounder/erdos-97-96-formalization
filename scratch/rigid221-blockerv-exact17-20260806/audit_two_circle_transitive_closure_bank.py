#!/usr/bin/env python3
"""Audit transitive two-circle bisector witnesses in exact-17 cap-nine banks.

This is a theorem-bank census, not a closure checker.  It independently
reconstructs the unordered-edge equality graph generated by each minimized
formalized-bank row set and measures the shortest row paths witnessing the
two equalities consumed by ``FourPointTwoCircleBisectorOrderCore``.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter, deque
from itertools import combinations
from pathlib import Path
from typing import Any

TARGET_STAGE = "equality-convex-four-point-two-circle-bisector-order"


def edge(left: int, right: int) -> tuple[int, int]:
    return (left, right) if left < right else (right, left)


def equality_graph(
    rows: list[dict[str, Any]],
) -> dict[tuple[int, int], list[tuple[tuple[int, int], int]]]:
    graph: dict[tuple[int, int], list[tuple[tuple[int, int], int]]] = {}
    for row_index, row in enumerate(rows):
        center = int(row["center"])
        nodes = [edge(center, int(point)) for point in row["support"]]
        for left, right in combinations(nodes, 2):
            graph.setdefault(left, []).append((right, row_index))
            graph.setdefault(right, []).append((left, row_index))
    return graph


def shortest_path(
    graph: dict[tuple[int, int], list[tuple[tuple[int, int], int]]],
    first: tuple[int, int],
    last: tuple[int, int],
) -> list[tuple[tuple[int, int], tuple[int, int], int]] | None:
    first = edge(*first)
    last = edge(*last)
    if first == last:
        return []
    queue = deque([first])
    parent: dict[
        tuple[int, int], tuple[tuple[int, int], int] | None
    ] = {first: None}
    while queue:
        current = queue.popleft()
        for successor, row_index in graph.get(current, []):
            if successor in parent:
                continue
            parent[successor] = (current, row_index)
            if successor == last:
                path = []
                cursor = last
                while cursor != first:
                    previous, used_row = parent[cursor]  # type: ignore[misc]
                    path.append((previous, cursor, used_row))
                    cursor = previous
                path.reverse()
                return path
            queue.append(successor)
    return None


def path_selected_atoms(
    path: list[tuple[tuple[int, int], tuple[int, int], int]],
    rows: list[dict[str, Any]],
) -> frozenset[tuple[int, int]]:
    """Return the oriented selected-row atoms used by an equality path."""

    atoms = set()
    for left, right, row_index in path:
        center = int(rows[row_index]["center"])
        for node in (left, right):
            assert center in node
            endpoint = node[1] if node[0] == center else node[0]
            atoms.add((center, endpoint))
    return frozenset(atoms)


def best_witness(
    rows: list[dict[str, Any]], order: tuple[int, ...]
) -> dict[str, Any] | None:
    graph = equality_graph(rows)
    best: tuple[tuple[int, ...], dict[str, Any]] | None = None
    for orientation, cyclic_order in (
        ("forward", order),
        ("reverse", tuple(reversed(order))),
    ):
        for start in range(len(cyclic_order)):
            rotated = cyclic_order[start:] + cyclic_order[:start]
            q = rotated[0]
            for i_u, i_y, i_v in combinations(range(1, len(rotated)), 3):
                u, y, v = rotated[i_u], rotated[i_y], rotated[i_v]
                first_path = shortest_path(graph, (q, u), (q, y))
                if first_path is None:
                    continue
                second_path = shortest_path(graph, (u, v), (y, v))
                if second_path is None:
                    continue
                atoms = path_selected_atoms(
                    first_path, rows
                ) | path_selected_atoms(second_path, rows)
                row_indices = sorted(
                    {step[2] for step in first_path + second_path}
                )
                score = (
                    max(len(first_path), len(second_path)),
                    len(first_path) + len(second_path),
                    len(atoms),
                    len(row_indices),
                )
                witness = {
                    "orientation": orientation,
                    "core": {"Q": q, "U": u, "Y": y, "V": v},
                    "path_lengths": [len(first_path), len(second_path)],
                    "atom_count": len(atoms),
                    "selected_atoms": [list(atom) for atom in sorted(atoms)],
                    "row_count": len(row_indices),
                }
                if best is None or score < best[0]:
                    best = (score, witness)
    return None if best is None else best[1]


def self_test() -> None:
    direct_rows = [
        {"center": 0, "support": [1, 2]},
        {"center": 3, "support": [1, 2]},
    ]
    direct = best_witness(direct_rows, (0, 1, 2, 3))
    assert direct is not None
    assert direct["path_lengths"] == [1, 1]

    transitive_rows = [
        {"center": 0, "support": [1, 4]},
        {"center": 4, "support": [0, 2]},
        {"center": 2, "support": [4, 0]},
    ]
    graph = equality_graph(transitive_rows)
    path = shortest_path(graph, (0, 1), (0, 2))
    assert path is not None and len(path) == 3
    assert shortest_path(graph, (0, 1), (0, 3)) is None


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("artifacts", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    self_test()

    files = sorted(args.artifacts.glob("*.json"))
    stage_entries = 0
    detected = 0
    direct = 0
    genuinely_transitive = 0
    path_pairs: Counter[tuple[int, int]] = Counter()
    atom_counts: Counter[int] = Counter()
    row_counts: Counter[int] = Counter()
    bounded = Counter()
    examples: dict[str, Any] = {}

    for artifact in files:
        payload = json.loads(artifact.read_text())
        order = tuple(int(label) for label in payload["order"])
        for learned in payload.get("learned", []):
            if learned.get("kind") != "formalized-bank":
                continue
            stage = str(learned["record"]["stage"])
            if not stage.startswith(TARGET_STAGE):
                continue
            stage_entries += 1
            witness = best_witness(learned["rows"], order)
            if witness is None:
                continue
            detected += 1
            pair = tuple(sorted(witness["path_lengths"]))
            if pair == (1, 1):
                direct += 1
            else:
                genuinely_transitive += 1
            path_pairs[pair] += 1
            atom_counts[witness["atom_count"]] += 1
            row_counts[witness["row_count"]] += 1
            for bound in range(1, 6):
                if max(pair) <= bound:
                    bounded[bound] += 1
            key = f"paths-{pair[0]}-{pair[1]}"
            examples.setdefault(
                key,
                {
                    "artifact": str(artifact),
                    "record": learned["record"],
                    "rows": learned["rows"],
                    "witness": witness,
                },
            )

    report = {
        "schema": "p97-exact17-cap9-two-circle-transitive-bank-audit-v1",
        "artifact_directory": str(args.artifacts),
        "artifact_count": len(files),
        "target_stage_entries": stage_entries,
        "independently_detected": detected,
        "undetected": stage_entries - detected,
        "direct_path_pair": direct,
        "genuinely_transitive": genuinely_transitive,
        "shortest_path_pair_distribution": {
            f"{left},{right}": count
            for (left, right), count in sorted(path_pairs.items())
        },
        "atom_count_distribution": dict(sorted(atom_counts.items())),
        "row_count_distribution": dict(sorted(row_counts.items())),
        "max_path_at_most": dict(sorted(bounded.items())),
        "examples": examples,
    }
    args.output.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    print(json.dumps({key: value for key, value in report.items() if key != "examples"}, indent=2))


if __name__ == "__main__":
    main()
