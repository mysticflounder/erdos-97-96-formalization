"""Minimize the corrected FreshThird exact-17 terminal SMT contradiction.

This is a discovery/audit tool.  It proves facts only about the frozen SMT
surface in the parent directory; it does not establish a Lean theorem or a
universal P97 conclusion.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import z3

HERE = Path(__file__).resolve().parent
PARENT = HERE.parent
GENERATED = HERE / "generated"
RESULTS = HERE / "results.json"
SHA256SUMS = HERE / "SHA256SUMS"

sys.path.insert(0, str(PARENT))
import refined_metric
import unified_metric as metric

CANONICAL_ARTIFACT = PARENT / "generated" / "refined_named_rows_and_singletons.smt2"


@dataclass(frozen=True)
class Query:
    name: str
    clauses: tuple[metric.Clause, ...]
    expected: str
    classification: str


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def parse_status(text: str) -> str:
    statuses = [
        line.strip()
        for line in text.splitlines()
        if line.strip() in {"sat", "unsat", "unknown"}
    ]
    if len(statuses) != 1:
        raise RuntimeError(f"expected one solver status, got {statuses!r}")
    return statuses[0].upper()


def python_solve(clauses: Iterable[metric.Clause], timeout_ms: int) -> tuple[str, str]:
    """Use a fresh QF_NRA solver and exactly validate any SAT model."""
    clauses = tuple(clauses)
    solver = z3.SolverFor("QF_NRA")
    solver.set(timeout=timeout_ms, random_seed=9717)
    solver.add(*[clause.formula for clause in clauses])
    verdict = solver.check()
    if verdict == z3.unknown:
        return f"UNKNOWN:{solver.reason_unknown()}", "NOT_RUN"
    if verdict == z3.unsat:
        return "UNSAT", "NOT_APPLICABLE"
    model = solver.model()
    failures = [
        clause.name
        for clause in clauses
        if not z3.is_true(model.eval(clause.formula, model_completion=True))
    ]
    return "SAT", "PASS" if not failures else "FAIL:" + ",".join(failures)


def extract_assumption_core(
    clauses: tuple[metric.Clause, ...], timeout_ms: int
) -> tuple[metric.Clause, ...]:
    """Extract a source-order core from a fresh implication/assumption solver."""
    solver = z3.SolverFor("QF_NRA")
    solver.set(timeout=timeout_ms, random_seed=9717, unsat_core=True)
    labels: list[z3.BoolRef] = []
    for index, clause in enumerate(clauses):
        label = z3.Bool(f"source_clause_{index:04d}")
        labels.append(label)
        solver.add(z3.Implies(label, clause.formula))
    verdict = solver.check(*labels)
    if verdict != z3.unsat:
        reason = solver.reason_unknown() if verdict == z3.unknown else str(verdict)
        raise RuntimeError(f"full tracked query did not return UNSAT: {reason}")
    selected = {str(label) for label in solver.unsat_core()}
    return tuple(
        clause
        for index, clause in enumerate(clauses)
        if f"source_clause_{index:04d}" in selected
    )


def deletion_minimize(
    candidate: tuple[metric.Clause, ...], timeout_ms: int
) -> tuple[tuple[metric.Clause, ...], list[dict[str, Any]]]:
    """Deletion-shrink with a fresh solver for every trial."""
    current = list(candidate)
    trials: list[dict[str, Any]] = []
    for clause in tuple(candidate):
        trial = tuple(item for item in current if item.name != clause.name)
        status, validation = python_solve(trial, timeout_ms)
        trials.append(
            {
                "dropped": clause.name,
                "remaining": [item.name for item in trial],
                "status": status,
                "exact_model_formula_evaluation": validation,
                "fresh_solver": True,
            }
        )
        if status == "UNSAT":
            current = list(trial)
        elif status != "SAT":
            raise RuntimeError(f"deletion trial for {clause.name} was {status}")
    minimized = tuple(current)
    status, _ = python_solve(minimized, timeout_ms)
    if status != "UNSAT":
        raise RuntimeError(f"minimized candidate was {status}")
    return minimized, trials


def artifact_text(clauses: Iterable[metric.Clause]) -> str:
    clauses = tuple(clauses)
    header = ["; generated by core_minimization/minimize_core.py"]
    for clause in clauses:
        header.append(f"; clause {clause.name} | source: {clause.source}")
    text = "\n".join(header) + "\n" + metric.one_check_smt2(clauses)
    if text.count("(check-sat)") != 1:
        raise RuntimeError("generated artifact does not contain exactly one check-sat")
    return text


def run_cli(command: list[str], timeout_s: int) -> dict[str, Any]:
    proc = subprocess.run(
        command,
        capture_output=True,
        text=True,
        timeout=timeout_s + 30,
        check=False,
    )
    return {
        "command": command,
        "status": parse_status(proc.stdout),
        "returncode": proc.returncode,
    }


def first_line(command: list[str]) -> str:
    proc = subprocess.run(command, capture_output=True, text=True, check=True)
    return (proc.stdout or proc.stderr).splitlines()[0].strip()


def write_and_replay(
    query: Query, timeout_ms: int, cvc5_timeout_ms: int
) -> dict[str, Any]:
    GENERATED.mkdir(parents=True, exist_ok=True)
    artifact = GENERATED / f"{query.name}.smt2"
    artifact.write_text(artifact_text(query.clauses))
    if artifact.read_text().count("(check-sat)") != 1:
        raise RuntimeError(f"one-check-sat integrity failed for {artifact}")
    python_status, validation = python_solve(query.clauses, timeout_ms)
    z3_cli = run_cli(
        ["z3", "-smt2", f"-T:{max(1, timeout_ms // 1000)}", str(artifact)],
        max(1, timeout_ms // 1000),
    )
    cvc5_cli = run_cli(
        [
            "cvc5",
            "--lang",
            "smt2",
            "--nl-cov",
            "--tlimit",
            str(cvc5_timeout_ms),
            str(artifact),
        ],
        max(1, cvc5_timeout_ms // 1000),
    )
    statuses = {python_status, z3_cli["status"], cvc5_cli["status"]}
    if statuses != {query.expected}:
        raise RuntimeError(f"{query.name}: expected {query.expected}, got {statuses}")
    if query.expected == "SAT" and validation != "PASS":
        raise RuntimeError(f"{query.name}: SAT model validation was {validation}")
    return {
        "name": query.name,
        "classification": query.classification,
        "expected": query.expected,
        "clause_count": len(query.clauses),
        "clauses": [clause.name for clause in query.clauses],
        "artifact": str(artifact.relative_to(HERE)),
        "sha256": sha256(artifact),
        "check_sat_count": 1,
        "python_z3": {
            "status": python_status,
            "exact_model_formula_evaluation": validation,
        },
        "z3_cli": z3_cli,
        "cvc5_cli": cvc5_cli,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--timeout-ms", type=int, default=60_000)
    parser.add_argument("--cvc5-timeout-ms", type=int, default=60_000)
    args = parser.parse_args()

    assignment = json.loads(refined_metric.ASSIGNMENT.read_text())
    errors = metric.validate_incidence_proposal(
        assignment
    ) + metric.validate_retained_first_apex_rich(assignment)
    if errors:
        raise RuntimeError("invalid canonical assignment: " + "; ".join(errors))
    encoding = metric.UnifiedEncoding(assignment)
    all_clauses = tuple(encoding.clauses_through("named_rows_and_singletons"))
    if len(all_clauses) != 1083:
        raise RuntimeError(f"expected 1083 canonical clauses, got {len(all_clauses)}")
    if metric.one_check_smt2(all_clauses).encode() != CANONICAL_ARTIFACT.read_bytes():
        raise RuntimeError(
            "rebuilt full artifact does not match canonical artifact byte-for-byte"
        )

    extracted = extract_assumption_core(all_clauses, args.timeout_ms)
    minimized, deletion_trials = deletion_minimize(extracted, args.timeout_ms)
    expected_names = {"k4_equal_13_10", "singleton_excludes_c_first_10"}
    if {clause.name for clause in minimized} != expected_names:
        raise RuntimeError(
            "unexpected minimized core: "
            + ", ".join(clause.name for clause in minimized)
        )
    by_name = {clause.name: clause for clause in all_clauses}
    k4 = by_name["k4_equal_13_10"]
    singleton = by_name["singleton_excludes_c_first_10"]
    by_formula: dict[str, list[str]] = {}
    for clause in all_clauses:
        by_formula.setdefault(z3.simplify(clause.formula).sexpr(), []).append(
            clause.name
        )
    opposite_pairs = sorted(
        {
            tuple(sorted((clause.name, other)))
            for clause in all_clauses
            for other in by_formula.get(z3.simplify(z3.Not(clause.formula)).sexpr(), [])
            if clause.name != other
        }
    )
    if opposite_pairs != [("k4_equal_13_10", "singleton_excludes_c_first_10")]:
        raise RuntimeError(
            f"unexpected direct syntactic opposite pairs: {opposite_pairs}"
        )

    # The broad stage groups (68 K4 clauses and 13 final-stage clauses) contain
    # many unrelated underconstrained nonlinear formulas.  Use the two smallest
    # source-local packets which still express the semantic producer/consumer
    # conflict.  Clause minimization below remains global over all 1083 inputs.
    k4_packet_names = {
        "k4_positive_13",
        "k4_equal_13_4",
        "k4_equal_13_10",
        "k4_equal_13_15",
    }
    singleton_packet_names = {
        "singleton_positive_c_first",
        "singleton_excludes_c_first_1",
        "singleton_excludes_c_first_7",
        "singleton_excludes_c_first_9",
        "singleton_excludes_c_first_10",
        "singleton_excludes_c_first_12",
    }
    group_k4 = tuple(clause for clause in all_clauses if clause.name in k4_packet_names)
    group_singletons = tuple(
        clause for clause in all_clauses if clause.name in singleton_packet_names
    )
    if {clause.name for clause in group_k4} != k4_packet_names:
        raise RuntimeError("failed to recover the exact first-apex K4 source packet")
    if {clause.name for clause in group_singletons} != singleton_packet_names:
        raise RuntimeError(
            "failed to recover the exact aligned c_first singleton packet"
        )
    smoke_x = z3.Real("smoke_x")
    queries = [
        Query(
            "minimized_clause_core",
            minimized,
            "UNSAT",
            "genuine deletion-minimal clause core",
        ),
        Query("drop_k4_equal_13_10", (singleton,), "SAT", "clause-minimality witness"),
        Query(
            "drop_singleton_excludes_c_first_10",
            (k4,),
            "SAT",
            "clause-minimality witness",
        ),
        Query(
            "named_group_core",
            group_k4 + group_singletons,
            "UNSAT",
            "deletion-minimal source-local named-packet core",
        ),
        Query(
            "named_group_drop_k4", group_singletons, "SAT", "group-minimality witness"
        ),
        Query(
            "named_group_drop_singletons", group_k4, "SAT", "group-minimality witness"
        ),
        Query(
            "malformed_flip_k4",
            (
                metric.Clause(
                    "malformed_not_k4_equal_13_10",
                    z3.Not(k4.formula),
                    "malformed control",
                ),
                singleton,
            ),
            "SAT",
            "malformed source-control: replace licensed K4 equality by its negation",
        ),
        Query(
            "malformed_flip_singleton",
            (
                k4,
                metric.Clause(
                    "malformed_not_singleton_excludes_c_first_10",
                    z3.Not(singleton.formula),
                    "malformed control",
                ),
            ),
            "SAT",
            "malformed source-control: replace licensed singleton exclusion by its negation",
        ),
        Query(
            "smoke_known_sat",
            (
                metric.Clause(
                    "smoke_x_eq_zero", smoke_x == 0, "known-result smoke control"
                ),
            ),
            "SAT",
            "known satisfiable smoke control",
        ),
        Query(
            "smoke_known_unsat",
            (
                metric.Clause(
                    "smoke_x_eq_zero", smoke_x == 0, "known-result smoke control"
                ),
                metric.Clause(
                    "smoke_x_eq_one", smoke_x == 1, "known-result smoke control"
                ),
            ),
            "UNSAT",
            "known unsatisfiable smoke control",
        ),
    ]
    replay = [
        write_and_replay(query, args.timeout_ms, args.cvc5_timeout_ms)
        for query in queries
    ]

    malformed_integrity = {
        "missing_check_sat": "REJECTED" if "".count("(check-sat)") != 1 else "FAIL",
        "duplicate_check_sat": "REJECTED"
        if "(check-sat)\n(check-sat)\n".count("(check-sat)") != 1
        else "FAIL",
    }
    if set(malformed_integrity.values()) != {"REJECTED"}:
        raise RuntimeError("malformed one-check-sat controls were not rejected")

    roles = assignment["roles"]
    result: dict[str, Any] = {
        "status": "DUAL_SOLVER_VERIFIED_DELETION_MINIMAL_CLAUSE_CORE",
        "scope": "one frozen corrected exact-17 FreshThird assignment only",
        "trust_rung": "computational theorem-discovery evidence; no Lean or universal closure claim",
        "canonical_input": {
            "artifact": str(CANONICAL_ARTIFACT.relative_to(PARENT)),
            "artifact_sha256": sha256(CANONICAL_ARTIFACT),
            "assignment": str(refined_metric.ASSIGNMENT.relative_to(PARENT)),
            "assignment_sha256": sha256(refined_metric.ASSIGNMENT),
            "encoder": "unified_metric.py",
            "encoder_sha256": sha256(PARENT / "unified_metric.py"),
            "clause_count": len(all_clauses),
            "byte_exact_rebuild": "PASS",
        },
        "solver_versions": {
            "python_z3": z3.get_version_string(),
            "z3_cli": first_line(["z3", "--version"]),
            "cvc5_cli": first_line(["cvc5", "--version"]),
        },
        "core_extraction": {
            "method": "Z3 assumption core followed by deterministic deletion shrink",
            "fresh_solver_per_deletion_trial": True,
            "initial_core": [clause.name for clause in extracted],
            "minimized_core": [clause.name for clause in minimized],
            "deletion_trials": deletion_trials,
        },
        "surviving_source_map": [
            {
                "clause": k4.name,
                "stage": "k4_witness_equalities",
                "source": k4.source,
                "formula": str(k4.formula),
                "meaning": (
                    f"D.K4 at first apex {roles['apex0']} has support "
                    "{0,4,10,15}; with base c_first=0, point 10 has the same "
                    "first-apex squared radius as c_first"
                ),
            },
            {
                "clause": singleton.name,
                "stage": "named_rows_and_singletons",
                "source": singleton.source,
                "formula": str(singleton.formula),
                "meaning": (
                    "aligned first-apex singleton slice for c_first=0 excludes "
                    "the distinct strict-first-cap point 10 from that radius"
                ),
            },
        ],
        "exact_source_level_conflict": (
            "The same two squared distances are required to be equal by the first-apex "
            "K4 witness row and unequal by the aligned c_first singleton slice."
        ),
        "direct_syntactic_opposite_pairs_in_all_1083_clauses": [
            list(pair) for pair in opposite_pairs
        ],
        "named_group_core": {
            "groups": [
                {
                    "name": "first_apex_k4_row_packet",
                    "clause_count": len(group_k4),
                    "clauses": [clause.name for clause in group_k4],
                },
                {
                    "name": "aligned_c_first_singleton_packet",
                    "clause_count": len(group_singletons),
                    "clauses": [clause.name for clause in group_singletons],
                },
            ],
            "deletion_minimal": True,
        },
        "stage_delta_distinction": {
            "final_stage_clause_count": len(
                encoding.groups["named_rows_and_singletons"]
            ),
            "source_local_singleton_packet_clause_count": len(group_singletons),
            "final_stage_is_not_the_core": True,
            "core_uses_final_stage_clauses": [singleton.name],
            "core_uses_prior_stage_clauses": [k4.name],
        },
        "replay": replay,
        "malformed_integrity_controls": malformed_integrity,
        "closure_claim": "NONE",
    }
    RESULTS.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")

    artifacts = sorted([RESULTS, *GENERATED.glob("*.smt2")], key=lambda path: str(path))
    SHA256SUMS.write_text(
        "".join(f"{sha256(path)}  {path.relative_to(HERE)}\n" for path in artifacts)
    )
    print(result["status"])
    print("core=" + ",".join(result["core_extraction"]["minimized_core"]))
    print(f"replayed={len(replay)} artifacts; hashes={SHA256SUMS.relative_to(HERE)}")


if __name__ == "__main__":
    main()
