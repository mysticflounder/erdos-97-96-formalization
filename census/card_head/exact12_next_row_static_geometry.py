"""Second static geometry layer for the exact-12 next-row lane.

Version 1 of the static compiler closes the equality relation generated by
selected rows and forbids duplicate three-point centres.  The first validated
v1 canary then exposed the next generic source theorem already present in the
Lean bank: the five-label equilateral-bisector collision.  This module keeps
the v1 byte contract intact and appends every labelled instance of that
theorem used by the detector as a clause over the same equality-relation
variables.  The detector's contract uses five pairwise distinct labels.

The extension is finite infrastructure, not a Lean proof.  Terminal promotion
still requires a source valuation assigning the auxiliary relation variables
from metric equality and proving that all v1 and v2 clauses evaluate to true.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from itertools import permutations

from .exact12_next_row_static_equality import (
    Exact12NextRowStaticEqualityError,
    StaticEqualityLayout,
    canonical_relation_assignment,
    clause_satisfied,
    install_static_duplicate_center_extension,
)
from .exact12_next_row_static_equality import (
    canonical_extension_satisfies_delta as equality_extension_satisfies_delta,
)
from .source_faithful_candidate_surface import SourceFaithfulCoverInstance

STATIC_GEOMETRY_SCHEMA = "p97_rigid221_exact12_next_row_static_geometry.v2"
SEMANTIC_STATUS = "FINITE_AUXILIARY_EXTENSION_REQUIRES_LEAN_VALUATION_BRIDGE"
LEAN_GEOMETRY_KERNEL = (
    "Problem97.Census554.EqualityCore."
    "not_realizes_of_equilateralBisectorCollisionCore"
)
LABEL_SCOPE = "five_pairwise_distinct_labels"

N = 12
EXPECTED_EQUILATERAL_BISECTOR_CLAUSES = 95_040


class Exact12NextRowStaticGeometryError(ValueError):
    """The v2 extension or its v1 parent violated the frozen contract."""


def _canonical_json_sha256(value: object) -> str:
    payload = json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=True
    ).encode("ascii")
    return hashlib.sha256(payload).hexdigest()


@dataclass(frozen=True)
class StaticGeometryLayout:
    """The immutable v1 equality layout plus the v2 geometric clause delta."""

    equality: StaticEqualityLayout
    equilateral_bisector_clauses: int
    geometry_clause_delta: tuple[tuple[int, ...], ...]
    final_n_variables: int
    final_n_clauses: int
    final_cnf_sha256: str
    geometry_clause_delta_sha256: str

    def manifest(self) -> dict[str, object]:
        return {
            "schema": STATIC_GEOMETRY_SCHEMA,
            "semantic_status": SEMANTIC_STATUS,
            "lean_geometry_kernel": LEAN_GEOMETRY_KERNEL,
            "label_scope": LABEL_SCOPE,
            "scope": (
                "exact-12 next-row static duplicate-center plus generic "
                "equilateral-bisector extension; not terminal UNSAT, aggregate "
                "coverage, or Lean closure"
            ),
            "parent": self.equality.manifest(),
            "counts": {
                "equilateral_bisector_clauses": self.equilateral_bisector_clauses,
                "added_variables": 0,
                "added_clauses": len(self.geometry_clause_delta),
                "final_variables": self.final_n_variables,
                "final_clauses": self.final_n_clauses,
            },
            "hashes": {
                "parent_final_cnf_sha256": self.equality.final_cnf_sha256,
                "geometry_clause_delta_sha256": (
                    self.geometry_clause_delta_sha256
                ),
                "final_cnf_sha256": self.final_cnf_sha256,
            },
        }


def install_static_geometry_extension(
    instance: SourceFaithfulCoverInstance,
) -> StaticGeometryLayout:
    """Install v1 equality closure and all generic equilateral-bisector cuts."""

    equality = install_static_duplicate_center_extension(instance)
    if hashlib.sha256(instance.dimacs().encode("ascii")).hexdigest() != (
        equality.final_cnf_sha256
    ):
        raise Exact12NextRowStaticGeometryError(
            "v1 equality formula changed before v2 installation"
        )

    edge_index = {edge: index for index, edge in enumerate(equality.edges)}

    def edge(left: int, right: int) -> int:
        return edge_index[tuple(sorted((left, right)))]

    def equal_variable(first_edge: int, second_edge: int) -> int:
        if first_edge == second_edge:
            raise Exact12NextRowStaticGeometryError(
                "equilateral-bisector schema compared one edge with itself"
            )
        key = tuple(sorted((first_edge, second_edge)))
        try:
            return equality.relation_variables[key]
        except KeyError as exc:
            raise Exact12NextRowStaticGeometryError(
                "v1 relation-variable map is incomplete"
            ) from exc

    initial_clause_count = len(instance.cnf.clauses)
    for p, a, b, c, x in permutations(range(N), 5):
        pa = edge(p, a)
        clause = tuple(
            -equal_variable(left, right)
            for left, right in (
                (pa, edge(p, b)),
                (pa, edge(p, c)),
                (pa, edge(a, b)),
                (pa, edge(a, x)),
                (pa, edge(b, x)),
                (edge(c, x), edge(c, a)),
            )
        )
        if len(set(clause)) != 6:
            raise Exact12NextRowStaticGeometryError(
                "equilateral-bisector clause collapsed relation literals"
            )
        instance.cnf.add_clause(clause)

    delta = tuple(instance.cnf.clauses[initial_clause_count:])
    if len(delta) != EXPECTED_EQUILATERAL_BISECTOR_CLAUSES:
        raise Exact12NextRowStaticGeometryError(
            "equilateral-bisector clause count drifted: "
            f"expected {EXPECTED_EQUILATERAL_BISECTOR_CLAUSES}, got {len(delta)}"
        )
    if len({tuple(sorted(clause)) for clause in delta}) != len(delta):
        raise Exact12NextRowStaticGeometryError(
            "equilateral-bisector compiler emitted duplicate CNF clauses"
        )

    layout = StaticGeometryLayout(
        equality=equality,
        equilateral_bisector_clauses=len(delta),
        geometry_clause_delta=delta,
        final_n_variables=instance.cnf.n_variables,
        final_n_clauses=len(instance.cnf.clauses),
        final_cnf_sha256=hashlib.sha256(
            instance.dimacs().encode("ascii")
        ).hexdigest(),
        geometry_clause_delta_sha256=_canonical_json_sha256(delta),
    )
    instance._exact12_next_row_static_geometry_layout = True
    return layout


def canonical_extension_satisfies_delta(
    instance: SourceFaithfulCoverInstance,
    layout: StaticGeometryLayout,
    cube: dict[int, list[int]],
) -> bool:
    """Check the canonical row-generated relation on both static layers."""

    try:
        equality_ok = equality_extension_satisfies_delta(
            instance, layout.equality, cube
        )
        selected = {
            instance.choice_variables[(
                center,
                instance.candidate_index(center, support),
            )]
            for center, support in cube.items()
        }
        true_variables = selected | set(
            canonical_relation_assignment(instance, layout.equality, cube)
        )
    except Exact12NextRowStaticEqualityError as exc:
        raise Exact12NextRowStaticGeometryError(str(exc)) from exc
    return equality_ok and all(
        clause_satisfied(clause, true_variables)
        for clause in layout.geometry_clause_delta
    )
