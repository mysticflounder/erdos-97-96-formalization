"""Authenticated center-exchange all-order common-five membership family.

For every role assignment ``a, b, c, x, y`` over all twelve labels that
satisfies the validated orbit side conditions ``a != b``, ``x != y``,
``x not in {a, b}``, ``y not in {a, b}``, ``c not in {b, x, y}`` and whose
five-point orientation holds in all forty-eight canonical zero-cut boundary
orders up to exchanging the two pair-centers — in every order the assignment
``(a, x, b, c, y)`` or its center exchange ``(a, y, b, c, x)`` is oriented —
the checked source producer refutes the positive rows

    x:{a,b}, y:{a,b}, c:{b,x,y}.

The family installs the center-exchange DELTA only: the widened orbit minus
every unordered pattern already admitted by the strict all-order rule under
either ordering.  The strict sub-orbit is already installed by the parent
all-order common-five bank, so the delta adds exactly the roles whose
orientation exchanges the two pair-centers between canonical orders.  The
roles enumeration mirrors ``centerExchangeRolesValid`` in the checked
certificate — the widened decidable check is ``centerExchangeOrientedAll48``,
a per-order disjunction of the assignment and its center exchange — and
reuses ``source_boundary_orders()`` as the single 48-order source of truth.
The widened orbit is 19,612 patterns, the strict orbit is 15,588 patterns
(all of them widened), and the full validated delta orbit is 4,024 patterns
over 1,878 distinct rows (617 pair + 1,261 triple) — EMPIRICAL, validated
against the independent crosscheck enumeration.  The bank installs the
realizable sub-orbit for this instance family: a role is dropped when any of
its three rows has no candidate realization on the frozen source-faithful
surface (``candidate_rows``).  An unrealizable row can never be selected in
any model of the formula, so dropping such patterns loses no blocking
strength.  Requirements already defined by ancestor banks reuse their
inherited pattern variables; the remaining requirements are fresh.  The
family appends the fresh implications followed by one three-literal block
per realizable role.

This is not terminal UNSAT, aggregate coverage, a universal lift, or live
closure.
"""

