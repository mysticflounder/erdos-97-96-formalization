"""Generate and inspect the six-role equilateral-chain blocking-clause orbit.

This module covers only the orbit generated by the directed membership motif

    A: {B, C, D}   B: {A, C, F}
    C: {A, D, E}   E: {C, D, F}.

Each injection of ``(A, B, C, D, E, F)`` into ``range(n)`` gives one clause
that blocks the simultaneous occurrence of its twelve membership atoms.  The
semantic source theorem is
``Problem97.false_of_realizes_three_equilateral_chain``.

The module neither constructs the unavailable augmented bank nor makes an
UNSAT claim about it.
"""

from __future__ import annotations

import argparse
import hashlib
import itertools
import json
import math
from collections.abc import Iterable, Iterator, Sequence
from pathlib import Path
from typing import BinaryIO

JSONL_FORMAT = "jsonl"
P97MONOTONE_FORMAT = "p97monotone"
SERIALIZATION_SCHEMA = "p97-strict-kalmanson-chain-bank-jsonl/v1"
P97MONOTONE_SCHEMA = "p97monotone/v1"
P97MONOTONE_SEMANTICS = (
    "custom monotone no-good bank of forbidden positive membership sets; "
    "not signed DIMACS CNF"
)
SEMANTIC_SOURCE_THEOREM = (
    "Problem97.false_of_realizes_three_equilateral_chain"
)
ROLE_NAMES = ("A", "B", "C", "D", "E", "F")
ROLE_INDEX = {role: index for index, role in enumerate(ROLE_NAMES)}
MOTIF_ROWS: dict[str, tuple[str, ...]] = {
    "A": ("B", "C", "D"),
    "B": ("A", "C", "F"),
    "C": ("A", "D", "E"),
    "E": ("C", "D", "F"),
}
MOTIF_ATOMS = tuple(
    (ROLE_INDEX[center], ROLE_INDEX[member])
    for center, members in MOTIF_ROWS.items()
    for member in members
)

Embedding = tuple[int, int, int, int, int, int]
Atom = tuple[int, int]
Clause = tuple[Atom, ...]


def _canonical_json_line(value: object) -> bytes:
    """Return the canonical UTF-8 JSON Lines representation of one record."""

    return (
        json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
        + "\n"
    ).encode("ascii")


def serialization_header(n: int) -> bytes:
    """Return the versioned first record of the deterministic clause stream."""

    _validate_n(n)
    return _canonical_json_line(
        {
            "atom": "directed membership [center,member]",
            "clause": "disjunction of negations of all listed atoms",
            "motif_atoms_by_role_index": [list(atom) for atom in MOTIF_ATOMS],
            "n": n,
            "record": "header",
            "role_order": list(ROLE_NAMES),
            "schema": SERIALIZATION_SCHEMA,
            "semantic_source_theorem": SEMANTIC_SOURCE_THEOREM,
        }
    )


def serialize_clause(clause: Clause) -> bytes:
    """Serialize one canonical blocking clause as a JSON Lines record."""

    return _canonical_json_line(
        {
            "atoms": [list(atom) for atom in clause],
            "record": "blocking_clause",
        }
    )


def membership_var(n: int, center: int, member: int) -> int:
    """Map a directed membership atom to its one-based p97monotone variable."""

    _validate_n(n)
    if any(
        isinstance(label, bool) or not isinstance(label, int)
        for label in (center, member)
    ):
        raise ValueError("center and member must be integers")
    if not (0 <= center < n and 0 <= member < n):
        raise ValueError("center and member must lie in range(n)")
    return 1 + n * center + member


def p97monotone_clause_ids(n: int, clause: Iterable[Atom]) -> tuple[int, ...]:
    """Return sorted variable IDs for one forbidden positive membership set."""

    return tuple(sorted({membership_var(n, center, member) for center, member in clause}))


def canonical_p97monotone_clauses(n: int) -> list[tuple[int, ...]]:
    """Return the globally sorted, duplicate-free compatibility clause bank."""

    clauses = sorted(
        {p97monotone_clause_ids(n, clause) for clause in iter_clauses(n)}
    )
    expected = expected_orbit_size(n)
    if len(clauses) != expected:
        raise AssertionError(
            f"generated {len(clauses)} distinct clauses, expected {expected}"
        )
    return clauses


def p97monotone_header(n: int, count: int) -> bytes:
    """Serialize the exact ASCII LF compatibility header."""

    _validate_n(n)
    if isinstance(count, bool) or not isinstance(count, int) or count < 0:
        raise ValueError("count must be a nonnegative integer")
    return f"p97monotone {n} {count}\n".encode("ascii")


def serialize_p97monotone_clause(clause_ids: Iterable[int]) -> bytes:
    """Serialize sorted positive IDs followed by the required terminal zero."""

    canonical = tuple(sorted(set(clause_ids)))
    if not canonical or any(
        isinstance(variable, bool) or not isinstance(variable, int) or variable <= 0
        for variable in canonical
    ):
        raise ValueError("p97monotone clause IDs must be positive integers")
    return (" ".join(map(str, canonical)) + " 0\n").encode("ascii")


def _validate_n(n: int) -> None:
    if isinstance(n, bool) or not isinstance(n, int) or n < len(ROLE_NAMES):
        raise ValueError(f"n must be an integer at least {len(ROLE_NAMES)}")


def expected_orbit_size(n: int) -> int:
    """Return P(n, 6), the number of injections of the six ordered roles."""

    _validate_n(n)
    return math.perm(n, len(ROLE_NAMES))


def clause_for_embedding(embedding: Sequence[int]) -> Clause:
    """Return the canonical twelve-atom clause for one role injection."""

    if len(embedding) != len(ROLE_NAMES):
        raise ValueError(f"embedding must have {len(ROLE_NAMES)} entries")
    labels = tuple(embedding)
    if any(isinstance(label, bool) or not isinstance(label, int) for label in labels):
        raise ValueError("embedding labels must be integers")
    if len(set(labels)) != len(ROLE_NAMES):
        raise ValueError("embedding labels must be distinct")
    return tuple(sorted((labels[center], labels[member]) for center, member in MOTIF_ATOMS))


def iter_embeddings(n: int) -> Iterator[Embedding]:
    """Yield all role injections in deterministic lexicographic order."""

    _validate_n(n)
    yield from itertools.permutations(range(n), len(ROLE_NAMES))


def iter_clauses(n: int) -> Iterator[Clause]:
    """Yield the canonical blocking clause for every role injection."""

    for embedding in iter_embeddings(n):
        yield clause_for_embedding(embedding)


def motif_automorphisms() -> tuple[Embedding, ...]:
    """Return every role permutation preserving the directed motif atoms."""

    atom_set = frozenset(MOTIF_ATOMS)
    automorphisms: list[Embedding] = []
    for permutation in itertools.permutations(range(len(ROLE_NAMES))):
        image = frozenset(
            (permutation[center], permutation[member])
            for center, member in MOTIF_ATOMS
        )
        if image == atom_set:
            automorphisms.append(permutation)
    return tuple(automorphisms)


def has_trivial_role_automorphism() -> bool:
    """Check that the directed motif has only the identity automorphism."""

    identity = tuple(range(len(ROLE_NAMES)))
    return motif_automorphisms() == (identity,)


def has_injective_clause_orbit() -> bool:
    """Check the finite certificate that distinct injections give distinct clauses.

    Every role occurs in an atom, so a labeled clause recovers the injection's
    six-label image.  If two injections gave the same clause, transporting one
    back through the other would therefore give a role automorphism.  The
    exhaustively computed automorphism group is trivial.
    """

    used_roles = {
        role_index for atom in MOTIF_ATOMS for role_index in atom
    }
    return used_roles == set(range(len(ROLE_NAMES))) and has_trivial_role_automorphism()


def _normalize_rows(rows: Sequence[Iterable[int]]) -> tuple[frozenset[int], ...]:
    n = len(rows)
    normalized: list[frozenset[int]] = []
    for center, members in enumerate(rows):
        try:
            row = frozenset(members)
        except TypeError as exc:
            raise ValueError(f"rows[{center}] must be iterable") from exc
        if any(
            isinstance(member, bool) or not isinstance(member, int)
            for member in row
        ):
            raise ValueError(f"rows[{center}] members must be integers")
        if any(member < 0 or member >= n for member in row):
            raise ValueError(f"rows[{center}] contains an out-of-range member")
        normalized.append(row)
    return tuple(normalized)


def find_motif_embeddings(rows: Sequence[Iterable[int]]) -> list[Embedding]:
    """Find ordered copies of the twelve directed atoms contained in ``rows``."""

    normalized = _normalize_rows(rows)
    n = len(normalized)
    if n < len(ROLE_NAMES):
        return []
    matches: list[Embedding] = []
    for embedding in iter_embeddings(n):
        if all(
            embedding[member] in normalized[embedding[center]]
            for center, member in MOTIF_ATOMS
        ):
            matches.append(embedding)
    return matches


def stream_orbit(n: int, output: BinaryIO | None = None) -> dict[str, object]:
    """Hash the deterministic stream, optionally writing its exact bytes."""

    _validate_n(n)
    automorphisms = motif_automorphisms()
    identity = tuple(range(len(ROLE_NAMES)))
    if automorphisms != (identity,):
        raise AssertionError(f"unexpected motif automorphisms: {automorphisms!r}")
    if not has_injective_clause_orbit():
        raise AssertionError("motif does not certify an injective clause orbit")
    if len(MOTIF_ATOMS) != 12 or len(set(MOTIF_ATOMS)) != 12:
        raise AssertionError("motif must contain twelve distinct directed atoms")

    digest = hashlib.sha256()
    byte_count = 0

    def consume(data: bytes) -> None:
        nonlocal byte_count
        digest.update(data)
        byte_count += len(data)
        if output is not None:
            output.write(data)

    consume(serialization_header(n))
    clause_count = 0
    for clause in iter_clauses(n):
        consume(serialize_clause(clause))
        clause_count += 1

    expected = expected_orbit_size(n)
    if clause_count != expected:
        raise AssertionError(f"generated {clause_count} clauses, expected {expected}")
    return {
        "atoms_per_clause": len(MOTIF_ATOMS),
        "clause_count": clause_count,
        "distinct_clause_count": clause_count,
        "distinctness_certificate": "trivial directed-role automorphism group",
        "n": n,
        "role_automorphisms": [list(item) for item in automorphisms],
        "schema": SERIALIZATION_SCHEMA,
        "semantic_source_theorem": SEMANTIC_SOURCE_THEOREM,
        "stream_bytes": byte_count,
        "stream_sha256": digest.hexdigest(),
    }


def stream_p97monotone(
    n: int, output: BinaryIO | None = None
) -> dict[str, object]:
    """Hash, and optionally write, the p97monotone compatibility stream.

    This is a custom monotone no-good bank.  Each line forbids the simultaneous
    truth of its listed positive membership variables; it is not signed DIMACS
    CNF.
    """

    clauses = canonical_p97monotone_clauses(n)
    digest = hashlib.sha256()
    byte_count = 0

    def consume(data: bytes) -> None:
        nonlocal byte_count
        digest.update(data)
        byte_count += len(data)
        if output is not None:
            output.write(data)

    consume(p97monotone_header(n, len(clauses)))
    for clause in clauses:
        consume(serialize_p97monotone_clause(clause))

    return {
        "atoms_per_clause": len(MOTIF_ATOMS),
        "clause_count": len(clauses),
        "distinct_clause_count": len(clauses),
        "format": P97MONOTONE_FORMAT,
        "format_semantics": P97MONOTONE_SEMANTICS,
        "n": n,
        "schema": P97MONOTONE_SCHEMA,
        "semantic_source_theorem": SEMANTIC_SOURCE_THEOREM,
        "stream_bytes": byte_count,
        "stream_sha256": digest.hexdigest(),
    }


def stream_bank(
    n: int, serialization_format: str = JSONL_FORMAT, output: BinaryIO | None = None
) -> dict[str, object]:
    """Dispatch to one of the explicitly named serialization formats."""

    if serialization_format == JSONL_FORMAT:
        return stream_orbit(n, output)
    if serialization_format == P97MONOTONE_FORMAT:
        return stream_p97monotone(n, output)
    raise ValueError(f"unknown serialization format: {serialization_format!r}")


def _load_survivor_embeddings(path: Path) -> list[Embedding]:
    with path.open("r", encoding="utf-8") as source:
        document = json.load(source)
    if not isinstance(document, dict) or "rows" not in document:
        raise ValueError("survivor JSON must be an object containing rows")
    rows = document["rows"]
    if not isinstance(rows, list):
        raise TypeError("survivor rows must be a list")
    return find_motif_embeddings(rows)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n", type=int, default=11)
    parser.add_argument(
        "--format",
        choices=(JSONL_FORMAT, P97MONOTONE_FORMAT),
        default=JSONL_FORMAT,
        help="serialization format (default: jsonl)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="write the selected stream; refuses to replace an existing path",
    )
    parser.add_argument(
        "--survivor",
        type=Path,
        help="also report all motif embeddings in a survivor JSON document",
    )
    args = parser.parse_args()

    if args.output is None:
        summary = stream_bank(args.n, args.format)
    else:
        with args.output.open("xb") as output:
            summary = stream_bank(args.n, args.format, output)
        summary["output"] = str(args.output)
    summary["claim_scope"] = "motif orbit only; no augmented-bank or UNSAT claim"
    if args.survivor is not None:
        embeddings = _load_survivor_embeddings(args.survivor)
        summary["survivor"] = {
            "embedding_count": len(embeddings),
            "embeddings": [list(embedding) for embedding in embeddings],
            "path": str(args.survivor),
        }
    print(json.dumps(summary, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
