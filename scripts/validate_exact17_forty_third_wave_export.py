def read_stable_bytes(path: Path) -> bytes:
    """Read one regular-file snapshot and reject replacement during the read."""
    before = os.lstat(path)
    try:
        descriptor = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    except OSError as error:
        raise ValueError(f"not a stable regular file: {path}") from error
    try:
        opened = os.fstat(descriptor)
        identity = lambda value: (
            value.st_dev,
            value.st_ino,
            value.st_mode,
            value.st_nlink,
            value.st_size,
            value.st_mtime_ns,
            value.st_ctime_ns,
        )
        if not stat.S_ISREG(opened.st_mode) or identity(before) != identity(opened):
            raise ValueError(f"not a stable regular file: {path}")
        chunks: list[bytes] = []
        while block := os.read(descriptor, 1024 * 1024):
            chunks.append(block)
        if identity(opened) != identity(os.fstat(descriptor)) or identity(opened) != identity(os.lstat(path)):
            raise ValueError(f"file changed while reading: {path}")
        return b"".join(chunks)
    finally:
        os.close(descriptor)


@contextmanager
def stable_binary_reader(path: Path) -> Iterator[tuple[BinaryIO, os.stat_result]]:
    """Yield one stable regular-file descriptor and recheck its path identity."""
    before = os.lstat(path)
    try:
        descriptor = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    except OSError as error:
        raise ValueError(f"not a stable regular file: {path}") from error
    opened = os.fstat(descriptor)
    identity = lambda value: (
        value.st_dev,
        value.st_ino,
        value.st_mode,
        value.st_nlink,
        value.st_size,
        value.st_mtime_ns,
        value.st_ctime_ns,
    )
    if not stat.S_ISREG(opened.st_mode) or identity(before) != identity(opened):
        os.close(descriptor)
        raise ValueError(f"not a stable regular file: {path}")
    handle = os.fdopen(descriptor, "rb")
    try:
        yield handle, opened
        if identity(opened) != identity(os.fstat(handle.fileno())) or identity(opened) != identity(os.lstat(path)):
            raise ValueError(f"file changed while reading: {path}")
    finally:
        handle.close()


