"""Generate and validate local strict-Kalmanson equality-collapse clauses.

The generator is solver-free.  It enumerates directed selected-membership
cores whose induced equality closure collapses at least one strict Kalmanson
comparison.  Only inclusion-minimal cores on exactly four or five cyclically
ordered roles are retained.

This is a candidate-catalog producer, not a reconstruction of the unavailable
42,504-clause n=11 bank.  In particular, the independently generated five-role
catalog is larger than the 130 five-role records forced by the Wave-5 n=12
aggregate count.  A source-faithful selector for those records is still needed.
"""

from __future__ import annotations

import argparse
import functools
import hashlib
import itertools
import json
import math
from collections import Counter
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import BinaryIO, Final, Literal

Atom = tuple[int, int]
Clause = tuple[Atom, ...]
Edge = tuple[int, int]
ComparisonKind = Literal["ab_cd", "ad_bc"]

CATALOG_SCHEMA: Final = "p97-strict-kalmanson-local-collapse-catalog/v1"
BANK_SCHEMA: Final = "p97-strict-kalmanson-local-collapse-bank-jsonl/v1"
P97MONOTONE_SCHEMA: Final = "p97monotone/v1"
P97MONOTONE_SEMANTICS: Final = (
    "custom monotone no-good bank of forbidden positive membership sets; "
    "not signed DIMACS CNF"
)
SUPPORTED_ROLE_COUNTS: Final = (4, 5)


@dataclass(frozen=True, order=True)
class KalmansonComparison:
    """One strict Kalmanson comparison on an increasing quadruple."""

    quadruple: tuple[int, int, int, int]
    kind: ComparisonKind
    left: tuple[Edge, Edge]
    right: tuple[Edge, Edge]


@dataclass(frozen=True, order=True)
class LocalCollapsePattern:
    """One canonical inclusion-minimal local equality-collapse core."""

    support_size: int
    atoms: Clause
    collapsed: tuple[KalmansonComparison, ...]

    @property
    def width(self) -> int:
        return len(self.atoms)

    @property
    def row_profile(self) -> tuple[int, ...]:
        counts = Counter(center for center, _member in self.atoms)
        return tuple(sorted(counts.values(), reverse=True))


def canonical_edge(first: int, second: int) -> Edge:
    """Return one unordered edge with increasing endpoints."""

    if first == second:
        raise ValueError("an edge must have distinct endpoints")
    return (first, second) if first < second else (second, first)


def canonical_clause(atoms: Iterable[Atom]) -> Clause:
    """Return a sorted, duplicate-free directed-membership clause."""

    clause = tuple(sorted(set(atoms)))
    if not clause:
        raise ValueError("a clause must contain at least one atom")
    if any(
        isinstance(label, bool) or not isinstance(label, int)
        for atom in clause
        for label in atom
    ):
        raise ValueError("atom labels must be integers")
    if any(center < 0 or member < 0 or center == member for center, member in clause):
        raise ValueError("atoms must have distinct nonnegative labels")
    return clause


def clause_support(clause: Iterable[Atom]) -> tuple[int, ...]:
    """Return the increasing tuple of all labels used by a clause."""

    return tuple(sorted({label for atom in clause for label in atom}))


def kalmanson_comparisons(role_count: int) -> tuple[KalmansonComparison, ...]:
    """Return both strict comparisons for every increasing quadruple."""

    _validate_role_count(role_count)
    result: list[KalmansonComparison] = []
    for a, b, c, d in itertools.combinations(range(role_count), 4):
        right = (canonical_edge(a, c), canonical_edge(b, d))
        result.extend(
            (
                KalmansonComparison(
                    (a, b, c, d),
                    "ab_cd",
                    (canonical_edge(a, b), canonical_edge(c, d)),
                    right,
                ),
                KalmansonComparison(
                    (a, b, c, d),
                    "ad_bc",
                    (canonical_edge(a, d), canonical_edge(b, c)),
                    right,
                ),
            )
        )
    return tuple(result)


def equality_components(role_count: int, clause: Clause) -> dict[Edge, Edge]:
    """Close the same-center equalities generated by selected atoms."""

    _validate_role_count(role_count)
    canonical = canonical_clause(clause)
    if any(label >= role_count for atom in canonical for label in atom):
        raise ValueError("clause label exceeds the role carrier")

    edges = tuple(itertools.combinations(range(role_count), 2))
    parent = {edge: edge for edge in edges}

    def find(edge: Edge) -> Edge:
        root = edge
        while parent[root] != root:
            root = parent[root]
        while parent[edge] != edge:
            successor = parent[edge]
            parent[edge] = root
            edge = successor
        return root

    def union(first: Edge, second: Edge) -> None:
        first_root = find(first)
        second_root = find(second)
        if first_root != second_root:
            parent[max(first_root, second_root)] = min(first_root, second_root)

    by_center: dict[int, list[Edge]] = {center: [] for center in range(role_count)}
    for center, member in canonical:
        by_center[center].append(canonical_edge(center, member))
    for incident in by_center.values():
        for edge in incident[1:]:
            union(incident[0], edge)
    return {edge: find(edge) for edge in edges}


def collapsed_comparisons(
    role_count: int, clause: Clause
) -> tuple[KalmansonComparison, ...]:
    """Return the comparisons whose two edge multisets close to the same pair."""

    components = equality_components(role_count, clause)
    return tuple(
        comparison
        for comparison in kalmanson_comparisons(role_count)
        if sorted(components[edge] for edge in comparison.left)
        == sorted(components[edge] for edge in comparison.right)
    )


def is_minimal_local_collapse(role_count: int, clause: Clause) -> bool:
    """Check exact support, collapse, and one-atom deletion minimality."""

    canonical = canonical_clause(clause)
    if any(label >= role_count for atom in canonical for label in atom):
        raise ValueError("clause label exceeds the role carrier")
    if clause_support(canonical) != tuple(range(role_count)):
        return False
    if not collapsed_comparisons(role_count, canonical):
        return False
    for index in range(len(canonical)):
        reduced = canonical[:index] + canonical[index + 1 :]
        if reduced and collapsed_comparisons(role_count, reduced):
            return False
    return True


def _row_choice_masks(role_count: int) -> tuple[tuple[int, ...], ...]:
    """Return row-local masks after deleting the inessential singleton case.

    A row represented by one atom generates no edge equality. Removing that
    atom leaves the equality closure unchanged, so such a row cannot occur in
    an inclusion-minimal collapse core.
    """

    atoms = _directed_atoms(role_count)
    atom_index = {atom: index for index, atom in enumerate(atoms)}
    rows: list[tuple[int, ...]] = []
    for center in range(role_count):
        outgoing = [(center, member) for member in range(role_count) if member != center]
        masks = [0]
        for width in range(2, len(outgoing) + 1):
            for chosen in itertools.combinations(outgoing, width):
                masks.append(sum(1 << atom_index[atom] for atom in chosen))
        rows.append(tuple(masks))
    return tuple(rows)


def _directed_atoms(role_count: int) -> tuple[Atom, ...]:
    return tuple(
        (center, member)
        for center in range(role_count)
        for member in range(role_count)
        if member != center
    )


def _clause_from_mask(role_count: int, mask: int) -> Clause:
    return tuple(
        atom
        for index, atom in enumerate(_directed_atoms(role_count))
        if mask & (1 << index)
    )


@functools.cache
def enumerate_minimal_local_collapses(
    role_count: int,
) -> tuple[LocalCollapsePattern, ...]:
    """Exhaust the reduced row-choice space for one exact support size."""

    _validate_role_count(role_count)
    patterns: list[LocalCollapsePattern] = []
    collapse_cache: dict[int, tuple[KalmansonComparison, ...]] = {}

    def collapses(mask: int) -> tuple[KalmansonComparison, ...]:
        if mask not in collapse_cache:
            clause = _clause_from_mask(role_count, mask)
            collapse_cache[mask] = (
                collapsed_comparisons(role_count, clause) if clause else ()
            )
        return collapse_cache[mask]

    for row_masks in itertools.product(*_row_choice_masks(role_count)):
        mask = 0
        for row_mask in row_masks:
            mask |= row_mask
        clause = _clause_from_mask(role_count, mask)
        if not clause or clause_support(clause) != tuple(range(role_count)):
            continue
        witnesses = collapses(mask)
        if not witnesses:
            continue
        if any(collapses(mask ^ (1 << bit)) for bit in range(mask.bit_length()) if mask & (1 << bit)):
            continue
        patterns.append(LocalCollapsePattern(role_count, clause, witnesses))
    return tuple(sorted(set(patterns)))


def candidate_catalog() -> tuple[LocalCollapsePattern, ...]:
    """Return the complete independently generated four/five-role candidate set."""

    return tuple(
        pattern
        for role_count in SUPPORTED_ROLE_COUNTS
        for pattern in enumerate_minimal_local_collapses(role_count)
    )


def count_matched_wave5_catalog() -> tuple[LocalCollapsePattern, ...]:
    """Return the unique width-class selection matching the Wave-5 totals.

    Independent enumeration gives all 12 four-role patterns and 190 five-role
    patterns, with 60 and only 60 of the five-role patterns having width ten.
    Removing that width class leaves the reported 142 records and, under
    increasing-subset lifting, the reported 108,900 local clauses at n=12.

    This count match does not authenticate the external catalog's membership.
    """

    return tuple(pattern for pattern in candidate_catalog() if pattern.width != 10)


def instantiate_pattern(
    pattern: LocalCollapsePattern, labels: Sequence[int]
) -> Clause:
    """Lift one ordered-role pattern along an increasing label subset."""

    embedding = tuple(labels)
    if len(embedding) != pattern.support_size:
        raise ValueError("embedding has the wrong support size")
    if embedding != tuple(sorted(embedding)) or len(set(embedding)) != len(embedding):
        raise ValueError("embedding labels must be strictly increasing")
    return canonical_clause(
        (embedding[center], embedding[member]) for center, member in pattern.atoms
    )


def candidate_local_bank(
    n: int, patterns: Iterable[LocalCollapsePattern] | None = None
) -> tuple[Clause, ...]:
    """Lift and globally deduplicate a local catalog on an n-label carrier."""

    _validate_n(n)
    inventory = candidate_catalog() if patterns is None else tuple(patterns)
    clauses = {
        instantiate_pattern(pattern, labels)
        for pattern in inventory
        for labels in itertools.combinations(range(n), pattern.support_size)
    }
    return tuple(sorted(clauses))


def complete_berge_bank(n: int) -> tuple[Clause, ...]:
    """Return the existing source-backed complete-Berge semantic family."""

    _validate_n(n)
    from generate_strict_kalmanson_known_clause_census import (
        classification_complete_berge_patterns,
        complete_berge_clauses,
        complete_berge_patterns,
        parse_three_equality_schemas,
    )

    patterns = complete_berge_patterns(parse_three_equality_schemas())
    if patterns != classification_complete_berge_patterns():
        raise ValueError("Lean-derived Berge patterns disagree with pinned classifier")
    clauses = complete_berge_clauses(n, patterns)
    return tuple(sorted(set(clauses)))


def count_matched_wave5_base_bank(n: int) -> tuple[Clause, ...]:
    """Combine the count-matched local catalog with complete Berge clauses."""

    local = set(candidate_local_bank(n, count_matched_wave5_catalog()))
    berge = set(complete_berge_bank(n))
    if local & berge:
        raise AssertionError("local support-at-most-five bank overlaps Berge")
    return tuple(sorted(local | berge))


def solve_two_support_histogram(
    *, n: int, record_count: int, lifted_count: int
) -> tuple[int, int]:
    """Solve counts on supports four/five under one-lift-per-subset semantics."""

    _validate_n(n)
    if record_count < 0 or lifted_count < 0:
        raise ValueError("counts must be nonnegative")
    solutions = [
        (four, record_count - four)
        for four in range(record_count + 1)
        if four * math.comb(n, 4) + (record_count - four) * math.comb(n, 5)
        == lifted_count
    ]
    if len(solutions) != 1:
        raise ValueError(f"expected one histogram solution, found {len(solutions)}")
    return solutions[0]


def membership_var(n: int, center: int, member: int) -> int:
    """Map one directed membership atom to a one-based p97monotone variable."""

    _validate_n(n)
    if not (0 <= center < n and 0 <= member < n) or center == member:
        raise ValueError("membership atom lies outside the carrier or is diagonal")
    return 1 + n * center + member


def p97monotone_clause_ids(n: int, clause: Clause) -> tuple[int, ...]:
    """Return the increasing variable IDs for one canonical clause."""

    return tuple(membership_var(n, center, member) for center, member in clause)


def _canonical_json_line(value: object) -> bytes:
    return (
        json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
        + "\n"
    ).encode("ascii")


def _comparison_record(comparison: KalmansonComparison) -> dict[str, object]:
    return {
        "kind": comparison.kind,
        "quadruple": list(comparison.quadruple),
    }


def serialize_catalog(patterns: Iterable[LocalCollapsePattern] | None = None) -> bytes:
    """Serialize the candidate pattern catalog as canonical ASCII JSON Lines."""

    inventory = candidate_catalog() if patterns is None else tuple(sorted(patterns))
    by_support = Counter(pattern.support_size for pattern in inventory)
    lines = [
        _canonical_json_line(
            {
                "atom": "directed selected membership [center,member]",
                "claim_scope": (
                    "independently enumerated minimal local equality collapses; "
                    "not the unavailable Wave-4 catalog"
                ),
                "pattern_count": len(inventory),
                "pattern_count_by_support": {
                    str(support): by_support[support] for support in sorted(by_support)
                },
                "record": "header",
                "schema": CATALOG_SCHEMA,
            }
        )
    ]
    lines.extend(
        _canonical_json_line(
            {
                "atoms": [list(atom) for atom in pattern.atoms],
                "collapsed_comparisons": [
                    _comparison_record(comparison)
                    for comparison in pattern.collapsed
                ],
                "record": "pattern",
                "row_profile": list(pattern.row_profile),
                "support_size": pattern.support_size,
                "width": pattern.width,
            }
        )
        for pattern in inventory
    )
    return b"".join(lines)


def serialize_bank_jsonl(n: int, clauses: Sequence[Clause]) -> bytes:
    """Serialize one deterministic lifted bank as canonical JSON Lines."""

    header = _canonical_json_line(
        {
            "atom": "directed selected membership [center,member]",
            "clause": "disjunction of negations of all listed atoms",
            "clause_count": len(clauses),
            "n": n,
            "record": "header",
            "schema": BANK_SCHEMA,
        }
    )
    return header + b"".join(
        _canonical_json_line(
            {"atoms": [list(atom) for atom in clause], "record": "blocking_clause"}
        )
        for clause in clauses
    )


def serialize_bank_p97monotone(n: int, clauses: Sequence[Clause]) -> bytes:
    """Serialize one lifted bank in the custom positive no-good format."""

    lines = [f"p97monotone {n} {len(clauses)}\n".encode("ascii")]
    for clause in clauses:
        ids = p97monotone_clause_ids(n, clause)
        lines.append((" ".join(map(str, ids)) + " 0\n").encode("ascii"))
    return b"".join(lines)


def catalog_summary(patterns: Iterable[LocalCollapsePattern] | None = None) -> dict[str, object]:
    """Return compact exact counts and the canonical catalog digest."""

    inventory = candidate_catalog() if patterns is None else tuple(sorted(patterns))
    body = serialize_catalog(inventory)
    return {
        "schema": CATALOG_SCHEMA,
        "pattern_count": len(inventory),
        "pattern_count_by_support": dict(sorted(Counter(p.support_size for p in inventory).items())),
        "width_histogram_by_support": {
            str(support): dict(
                sorted(Counter(p.width for p in inventory if p.support_size == support).items())
            )
            for support in sorted({p.support_size for p in inventory})
        },
        "row_profile_histogram_by_support": {
            str(support): {
                ",".join(map(str, profile)): count
                for profile, count in sorted(
                    Counter(
                        p.row_profile
                        for p in inventory
                        if p.support_size == support
                    ).items()
                )
            }
            for support in sorted({p.support_size for p in inventory})
        },
        "catalog_bytes": len(body),
        "catalog_sha256": hashlib.sha256(body).hexdigest(),
        "claim_scope": (
            "candidate catalog only; no identity with the Wave-4 catalog or "
            "the announced n=11 base is asserted"
        ),
    }


def _validate_role_count(role_count: int) -> None:
    if role_count not in SUPPORTED_ROLE_COUNTS:
        raise ValueError(f"role_count must be one of {SUPPORTED_ROLE_COUNTS}")


def _validate_n(n: int) -> None:
    if isinstance(n, bool) or not isinstance(n, int) or n < max(SUPPORTED_ROLE_COUNTS):
        raise ValueError(f"n must be an integer at least {max(SUPPORTED_ROLE_COUNTS)}")


def _write_exclusive(path: Path, payload: bytes) -> None:
    with path.open("xb") as stream:
        _write_all(stream, payload)


def _write_all(stream: BinaryIO, payload: bytes) -> None:
    written = stream.write(payload)
    if written != len(payload):
        raise OSError(f"short write: wrote {written} of {len(payload)} bytes")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=("catalog", "bank"), default="catalog")
    parser.add_argument("--n", type=int, default=12)
    parser.add_argument("--format", choices=("jsonl", "p97monotone"), default="jsonl")
    parser.add_argument(
        "--catalog-policy",
        choices=("all-minimal", "wave5-count-matched"),
        default="all-minimal",
    )
    parser.add_argument("--include-berge", action="store_true")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()

    inventory = (
        candidate_catalog()
        if args.catalog_policy == "all-minimal"
        else count_matched_wave5_catalog()
    )
    if args.mode == "catalog":
        if args.format != "jsonl":
            parser.error("catalog mode supports only --format jsonl")
        payload = serialize_catalog(inventory)
        summary = catalog_summary(inventory)
    else:
        clauses = candidate_local_bank(args.n, inventory)
        if args.include_berge:
            clauses = tuple(sorted(set(clauses) | set(complete_berge_bank(args.n))))
        payload = (
            serialize_bank_jsonl(args.n, clauses)
            if args.format == "jsonl"
            else serialize_bank_p97monotone(args.n, clauses)
        )
        summary = {
            "schema": BANK_SCHEMA if args.format == "jsonl" else P97MONOTONE_SCHEMA,
            "semantics": P97MONOTONE_SEMANTICS,
            "n": args.n,
            "clause_count": len(clauses),
            "output_bytes": len(payload),
            "output_sha256": hashlib.sha256(payload).hexdigest(),
            "catalog_policy": args.catalog_policy,
            "include_berge": args.include_berge,
            "claim_scope": (
                "count-matched reconstruction candidate only; no source identity "
                "or UNSAT claim"
                if args.catalog_policy == "wave5-count-matched"
                else "candidate local-collapse bank only; no UNSAT claim"
            ),
        }
    if args.output is not None:
        _write_exclusive(args.output, payload)
        summary["output_path"] = str(args.output)
    print(json.dumps(summary, sort_keys=True, separators=(",", ":")))


if __name__ == "__main__":
    main()
